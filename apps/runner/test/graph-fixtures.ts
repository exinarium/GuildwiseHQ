export interface GraphFixture {
  repo: string;
  repoKey: string;
  commit: string;
}

export function writeFiles(root: string, files: Record<string, string>): void {
  for (const [rel, content] of Object.entries(files)) {
    const f = join(root, rel);
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(f, content);
  }
}

export function makeGraphRepo(files: Record<string, string> = FIXTURE_FILES): GraphFixture {
  const repo = tmp('aom-graph-repo-');
  sh(repo, 'git', ['init', '-b', 'main']);
  writeFiles(repo, files);
  sh(repo, 'git', ['add', '-A', '-f']);
  sh(repo, 'git', ['commit', '-m', 'fixture']);
  return {
    repo,
    repoKey: graphRepoKey('github.com/acme/fixture'),
    commit: sh(repo, 'git', ['rev-parse', 'HEAD']),
  };
}
