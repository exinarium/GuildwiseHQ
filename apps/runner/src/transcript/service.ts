import { slugify, type TranscriptRef } from '@aom/shared';
import {
  fetchTranscript,
  MAX_TRANSCRIPT_CHARS,
  spawnExec,
  type TranscriptDeps,
  type TranscriptResult,
  transcriptHeader,
} from './fetch.ts';

export const defaultTranscriptDeps = (): TranscriptDeps => ({ exec: spawnExec, fetch });

/** Deterministic stand-in for the mock runtime: a fake transcript, or none when the URL says `no-transcript`. */
export function mockTranscript(url: string): TranscriptResult {
  if (/no-transcript/.test(url))
    return { status: 'none', url, message: 'mock: this source has no transcript' };
  return {
    status: 'ok',
    url,
    title: 'Mock transcript',
    source: 'mock',
    language: 'en',
    autoGenerated: true,
    text: `Welcome to the mock talk at ${url}.\n\nToday we cover reloading density and why it matters. The key claim is that mock transcripts are fake.`,
    truncated: false,
  };
}

/** `projects/<name>/transcripts/<yyyy-mm-dd>-<slug>.md` (a short hash of the URL keeps two same-titled items apart). */
export function transcriptPath(folder: string, at: Date, title: string, url: string): string {
  let h = 5381;
  for (const ch of url) h = ((h << 5) + h + ch.charCodeAt(0)) >>> 0;
  const slug = slugify(title, 50) || 'transcript';
  return `${folder}/transcripts/${at.toISOString().slice(0, 10)}-${slug}-${h.toString(36).slice(-4)}.md`;
}

const q = (s: string) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\s+/g, ' ').trim()}"`;

/** The vault file: front matter (what the header says) and the text. */
export function renderTranscriptFile(r: TranscriptResult, fetched: Date): string {
  return [
    '---',
    `title: ${q(r.title ?? r.url)}`,
    `url: ${r.url}`,
    `source: ${q(r.source ?? '')}`,
    `language: ${r.language ?? 'unknown'}`,
    `autoGenerated: ${r.autoGenerated ?? 'unknown'}`,
    `fetched: ${fetched.toISOString().slice(0, 10)}`,
    ...(r.truncated ? [`truncated: ${MAX_TRANSCRIPT_CHARS}`] : []),
    '---',
    '',
    `# ${(r.title ?? r.url).replace(/\s+/g, ' ')}`,
    '',
    r.text ?? '',
    '',
  ].join('\n');
}

export const refOf = (r: TranscriptResult, path?: string): TranscriptRef =>
  r.status === 'ok'
    ? {
        status: 'ok',
        ...(path ? { path } : {}),
        chars: r.text?.length ?? 0,
        ...(r.autoGenerated !== undefined ? { autoGenerated: r.autoGenerated } : {}),
      }
    : { status: r.status === 'none' ? 'none' : 'error' };

/** How much of the transcript `aom transcript` prints for the agent (the whole text is in the vault file). */
export const PRINT_CHARS = 30_000;

/** What `aom transcript` prints. */
export function renderTranscriptMessage(r: TranscriptResult, path?: string): string {
  if (r.status === 'tool_missing')
    return `transcript tool missing: yt-dlp\nStatus: tool_missing\nAsk the DevOps engineer: aom devops "install yt-dlp"`;
  if (r.status === 'none')
    return `no transcript available\nStatus: none\nURL: ${r.url}${r.message ? `\nReason: ${r.message}` : ''}`;
  if (r.status === 'error')
    return `transcript lookup failed\nStatus: error\nURL: ${r.url}${r.message ? `\nReason: ${r.message}` : ''}`;
  const text = r.text ?? '';
  const shown = text.length > PRINT_CHARS;
  return [
    'Status: ok',
    transcriptHeader(r),
    ...(path ? [`Saved: ${path}`] : []),
    `Length: ${text.length} characters${r.truncated ? ' (truncated at the cap)' : ''}`,
    '',
    shown
      ? `${text.slice(0, PRINT_CHARS)}\n\n[showing the first ${PRINT_CHARS} characters; the whole transcript is saved${path ? ` in ${path}` : ''}]`
      : text,
  ].join('\n');
}

