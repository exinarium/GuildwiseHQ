// `aom transcript`: finds the transcript of a video or podcast episode. Runs in the runner process, outside the
// agent sandbox, so the agent's network allowlist does not apply. Never invents text: no transcript is a result.
import { spawn } from 'node:child_process';
import { mkdtemp, readdir, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { decodeEntities, transcriptToText } from './convert.ts';

export const MAX_TRANSCRIPT_CHARS = 200_000;
export const YTDLP_TIMEOUT_MS = 120_000;
const HTTP_TIMEOUT_MS = 20_000;
const MAX_FETCH_BYTES = 8_000_000;

export type TranscriptStatus = 'ok' | 'none' | 'tool_missing' | 'error';

export interface TranscriptResult {
  status: TranscriptStatus;
  url: string;
  title?: string;
  source?: string;
  language?: string;
  autoGenerated?: boolean;
  /** Plain text, already capped at {@link MAX_TRANSCRIPT_CHARS}. */
  text?: string;
  truncated?: boolean;
  /** Why there is none, or what went wrong. */
  message?: string;
}

export interface ExecResult {
  code: number | null;
  stdout: string;
  stderr: string;
  /** The binary does not exist. */
  missing?: boolean;
  timedOut?: boolean;
}
export type Exec = (
  cmd: string,
  args: string[],
  opts: { timeoutMs: number; cwd?: string },
) => Promise<ExecResult>;

export interface TranscriptDeps {
  exec: Exec;
  fetch: typeof fetch;
}

/** Spawns a process with a timeout; a missing binary is reported, not thrown. */
export const spawnExec: Exec = (cmd, args, opts) =>
  new Promise((resolve) => {
    let out = '';
    let err = '';
    let timedOut = false;
    const child = spawn(cmd, args, {
      stdio: ['ignore', 'pipe', 'pipe'],
      ...(opts.cwd ? { cwd: opts.cwd } : {}),
    });
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill('SIGKILL');
    }, opts.timeoutMs);
    child.stdout.on('data', (d: Buffer) => {
      if (out.length < 2_000_000) out += d.toString('utf8');
    });
    child.stderr.on('data', (d: Buffer) => {
      if (err.length < 200_000) err += d.toString('utf8');
    });
    child.on('error', (e: NodeJS.ErrnoException) => {
      clearTimeout(timer);
      resolve({ code: null, stdout: out, stderr: err || e.message, missing: e.code === 'ENOENT' });
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      resolve({ code, stdout: out, stderr: err, timedOut });
    });
  });

const VIDEO_HOST =
  /(^|\.)(youtube\.com|youtu\.be|youtube-nocookie\.com|vimeo\.com|dailymotion\.com|twitch\.tv|ted\.com|bilibili\.com|facebook\.com|x\.com|twitter\.com)$/i;

/** Hosts where yt-dlp is the way to get captions (anything else is first searched for a published transcript). */
export const isVideoHost = (url: string): boolean => {
  try {
    return VIDEO_HOST.test(new URL(url).hostname);
  } catch {
    return false;
  }
};

export function capText(text: string): { text: string; truncated: boolean } {
  if (text.length <= MAX_TRANSCRIPT_CHARS) return { text, truncated: false };
  return {
    text: `${text.slice(0, MAX_TRANSCRIPT_CHARS).trimEnd()}\n\n[transcript truncated at ${MAX_TRANSCRIPT_CHARS} characters]`,
    truncated: true,
  };
}

// ----------------------------------------------------------------------------- published transcripts (podcasts)

interface TranscriptLink {
  url: string;
  type: string;
}

const TYPE_ORDER = [
  'text/vtt',
  'application/x-subrip',
  'application/srt',
  'application/json',
  'text/html',
  'text/plain',
];

/** `<podcast:transcript url="..." type="..."/>` tags of a feed or page. */
export function podcastTranscriptLinks(xml: string, base: string): TranscriptLink[] {
  const out: TranscriptLink[] = [];
  for (const m of xml.matchAll(/<podcast:transcript\b([^>]*)>/gi)) {
    const attrs = m[1] as string;
    const url = /\burl\s*=\s*["']([^"']+)["']/i.exec(attrs)?.[1];
    if (!url) continue;
    const type = /\btype\s*=\s*["']([^"']+)["']/i.exec(attrs)?.[1] ?? '';
    const abs = absolute(decodeEntities(url), base);
    if (abs) out.push({ url: abs, type: type.toLowerCase() });
  }
  return out.sort((a, b) => rank(a.type) - rank(b.type));
}

/** Links in an HTML page that point to a transcript: `<link rel=alternate type=text/vtt>` or an anchor that says "transcript". */
export function htmlTranscriptLinks(html: string, base: string): TranscriptLink[] {
  const out: TranscriptLink[] = [];
  for (const m of html.matchAll(/<link\b([^>]*)>/gi)) {
    const attrs = m[1] as string;
    const type = /\btype\s*=\s*["']([^"']+)["']/i.exec(attrs)?.[1]?.toLowerCase() ?? '';
    const href = /\bhref\s*=\s*["']([^"']+)["']/i.exec(attrs)?.[1];
    if (href && /vtt|srt|subrip/.test(type) && /alternate/i.test(attrs)) {
      const abs = absolute(decodeEntities(href), base);
      if (abs) out.push({ url: abs, type });
    }
  }
  for (const m of html.matchAll(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi)) {
    const href = /\bhref\s*=\s*["']([^"']+)["']/i.exec(m[1] as string)?.[1];
    const label = (m[2] as string).replace(/<[^>]*>/g, ' ');
    if (href && /\btranscript\b/i.test(label)) {
      const abs = absolute(decodeEntities(href), base);
      if (abs && abs !== base) out.push({ url: abs, type: guessType(abs) });
    }
  }
  return out.sort((a, b) => rank(a.type) - rank(b.type));
}

const rank = (t: string): number => {
  const i = TYPE_ORDER.indexOf(t);
  return i === -1 ? TYPE_ORDER.length : i;
};
const guessType = (u: string): string => {
  const p = u.toLowerCase().split('?')[0] ?? '';
  return p.endsWith('.vtt')
    ? 'text/vtt'
    : p.endsWith('.srt')
      ? 'application/x-subrip'
      : p.endsWith('.json')
        ? 'application/json'
        : '';
};
function absolute(u: string, base: string): string | undefined {
  try {
    const r = new URL(u, base);
    return r.protocol === 'http:' || r.protocol === 'https:' ? r.href : undefined;
  } catch {
    return undefined;
  }
}

async function getText(
  deps: TranscriptDeps,
  url: string,
): Promise<{ text: string; contentType: string } | undefined> {
  try {
    const res = await deps.fetch(url, {
      redirect: 'follow',
      signal: AbortSignal.timeout(HTTP_TIMEOUT_MS),
      headers: { 'user-agent': 'aom-runner/transcript', accept: '*/*' },
    });
    if (!res.ok) return undefined;
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length > MAX_FETCH_BYTES) return undefined;
    return { text: buf.toString('utf8'), contentType: res.headers.get('content-type') ?? '' };
  } catch {
    return undefined;
  }
}

const titleOf = (html: string): string | undefined => {
  const og = /<meta[^>]+property=["']og:title["'][^>]+content=["']([^"']+)["']/i.exec(html)?.[1];
  const t = og ?? /<title[^>]*>([\s\S]*?)<\/title>/i.exec(html)?.[1];
  return t ? decodeEntities(t).replace(/\s+/g, ' ').trim().slice(0, 300) : undefined;
};

/** A transcript the page or feed itself links to (`<podcast:transcript>`, a VTT/SRT alternate, a "Transcript" link). */
async function publishedTranscript(deps: TranscriptDeps, url: string): Promise<TranscriptResult | undefined> {
  const page = await getText(deps, url);
  if (!page) return undefined;
  const isMarkup = /xml|html|rss/i.test(page.contentType) || /^\s*</.test(page.text);
  if (!isMarkup) {
    // the URL itself is a transcript file
    const text = transcriptToText(page.text, { contentType: page.contentType, url });
    return text.trim().length > 20
      ? { status: 'ok', url, title: url, text, autoGenerated: false }
      : undefined;
  }
  const links = [...podcastTranscriptLinks(page.text, url), ...htmlTranscriptLinks(page.text, url)];
  for (const link of links.slice(0, 4)) {
    const got = await getText(deps, link.url);
    if (!got) continue;
    const text = transcriptToText(got.text, { contentType: got.contentType || link.type, url: link.url });
    if (text.trim().length > 20)
      return {
        status: 'ok',
        url,
        title: titleOf(page.text) ?? url,
        source: new URL(url).hostname,
        text,
        autoGenerated: false,
      };
  }
  return undefined;
}

// ------------------------------------------------------------------------------------------------- yt-dlp

/** Captions through yt-dlp (`--skip-download`): manual subtitles are preferred over auto-generated ones. */
async function viaYtDlp(deps: TranscriptDeps, url: string): Promise<TranscriptResult> {
  const dir = await mkdtemp(join(tmpdir(), 'aom-transcript-'));
  try {
    const r = await deps.exec(
      'yt-dlp',
      [
        '--skip-download',
        '--no-simulate',
        '--no-playlist',
        '--write-subs',
        '--write-auto-subs',
        '--sub-langs',
        'en.*,en',
        '--sub-format',
        'vtt',
        '--no-warnings',
        '--print',
        '%(title)s',
        '--print',
        '%(channel,uploader)s',
        '--print',
        '%(subtitles)j',
        '-o',
        join(dir, '%(id)s.%(ext)s'),
        url,
      ],
      { timeoutMs: YTDLP_TIMEOUT_MS },
    );
    if (r.missing) return { status: 'tool_missing', url, message: 'transcript tool missing: yt-dlp' };
    if (r.timedOut)
      return { status: 'error', url, message: `yt-dlp timed out after ${YTDLP_TIMEOUT_MS / 1000}s` };
    const files = (await readdir(dir)).filter((f) => f.endsWith('.vtt')).sort();
    if (r.code !== 0 && files.length === 0) {
      const msg = r.stderr.trim().split('\n').slice(-2).join(' ').slice(0, 300);
      return { status: 'error', url, message: `yt-dlp failed${msg ? `: ${msg}` : ''}` };
    }
    const [title = url, source, subsJson] = r.stdout.split('\n');
    if (files.length === 0) return { status: 'none', url, title, message: 'no captions found' };
    // pick the plain English track: `<id>.en.vtt` before `<id>.en-US.vtt`, `en-orig`, ...
    const file = files.find((f) => /\.en\.vtt$/.test(f)) ?? files[0] ?? '';
    const language = /\.([A-Za-z-]+)\.vtt$/.exec(file)?.[1] ?? 'en';
    const text = transcriptToText(await readFile(join(dir, file), 'utf8'), { url: file });
    if (text.trim().length === 0) return { status: 'none', url, title, message: 'the captions were empty' };
    let manual = false;
    try {
      const subs = JSON.parse(subsJson ?? '{}') as Record<string, unknown> | null;
      manual = !!subs && Object.keys(subs).some((k) => k === language || k.startsWith('en'));
    } catch {
      manual = false;
    }
    return {
      status: 'ok',
      url,
      title,
      ...(source && source !== 'NA' ? { source } : {}),
      language,
      autoGenerated: !manual,
      text,
    };
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
}

/** Finds the transcript of a video or podcast URL. Never throws; never invents text. */
export async function fetchTranscript(url: string, deps: TranscriptDeps): Promise<TranscriptResult> {
  let result: TranscriptResult;
  try {
    new URL(url);
    if (isVideoHost(url)) result = await viaYtDlp(deps, url);
    else {
      const published = await publishedTranscript(deps, url);
      if (published) result = published;
      else {
        const viaTool = await viaYtDlp(deps, url);
        // A non-video page without yt-dlp simply has no transcript we can reach.
        result =
          viaTool.status === 'tool_missing' || viaTool.status === 'error'
            ? { status: 'none', url, message: 'the page and its feed expose no transcript' }
            : viaTool;
      }
    }
  } catch (err) {
    result = { status: 'error', url, message: err instanceof Error ? err.message : String(err) };
  }
  if (result.status === 'ok' && result.text) {
    const capped = capText(result.text);
    result = { ...result, text: capped.text, truncated: capped.truncated };
  }
  return result;
}

/** The short header printed above the transcript (and stored in the vault file's front matter). */
export function transcriptHeader(r: TranscriptResult): string {
  return [
    `Title: ${r.title ?? r.url}`,
    `Source: ${r.source ?? new URL(r.url).hostname} (${r.url})`,
    `Language: ${r.language ?? 'unknown'}`,
    `Captions: ${r.autoGenerated === undefined ? 'unknown' : r.autoGenerated ? 'auto-generated' : 'published by the author'}`,
  ].join('\n');
}
