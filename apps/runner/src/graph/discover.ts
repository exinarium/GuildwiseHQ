import { looksLikeSecret } from '@aom/shared';
import type { TreeEntry } from './types.ts';

/** Files above this size are not read (generated bundles, data dumps). */
export const MAX_FILE_BYTES = 1_000_000;

/** Folders that hold dependencies or build output: never indexed. */
const SKIPPED_DIRS = new Set([
  'node_modules',
  'vendor',
  'dist',
  'build',
  'out',
  'bin',
  'obj',
  '.venv',
  'venv',
  '__pycache__',
  '.git',
  '.next',
  '.nuxt',
  '.turbo',
  '.cache',
  '.gradle',
  'target',
  'coverage',
  'packages-lock',
  'bower_components',
  'site-packages',
  '.idea',
  '.vs',
]);

/** Folders that hold credentials or keys. */
const SENSITIVE_DIRS = new Set([
  '.ssh',
  '.aws',
  '.gnupg',
  '.kube',
  '.azure',
  '.docker',
  '.gcloud',
  '.secrets',
]);

/** Data-like files whose name says they hold secrets (a code file named `secrets.ts` is code and is indexed). */
const SECRET_DATA_NAME =
  /(secret|credential|passwd|password|token|private[-_.]?key|service[-_.]?account|apikey|api[-_.]key)/i;
const DATA_EXT = /\.(json|ya?ml|toml|ini|cfg|conf|xml|properties|txt|csv|env|plist|tfvars|tfstate)$/i;
const SECRET_FIXED =
  /^(\.env.*|\.netrc|\.npmrc|\.pypirc|\.htpasswd|kubeconfig|id_(rsa|dsa|ecdsa|ed25519).*|.*\.(pem|key|p12|pfx|jks|keystore|ppk|asc|gpg|kdbx|tfvars|tfstate))$/i;

/** The lock files and minified output the graph never reads. */
const NOISE =
  /(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|npm-shrinkwrap\.json|go\.sum|poetry\.lock|Cargo\.lock|composer\.lock)$|\.min\.(js|css)$|\.(map|snap)$/i;

const BINARY_EXT =
  /\.(png|jpe?g|gif|webp|ico|bmp|tiff?|svgz?|pdf|zip|gz|tgz|bz2|xz|7z|rar|jar|war|dll|exe|so|dylib|a|o|class|pyc|wasm|woff2?|ttf|otf|eot|mp[34]|mov|avi|webm|wav|ogg|bin|dat|db|sqlite3?|lock)$/i;

const GENERATED_NAME =
  /(\.g\.cs|\.designer\.cs|\.generated\.[a-z]+|_pb2\.py|\.pb\.go|_generated\.go|\.d\.ts)$/i;

/** First bytes that mark a file as generated (checked on the content the parser reads). */
export const GENERATED_MARKER =
  /(^|\n)\s*(\/\/|#|\/\*+|\*)\s*(<auto-generated|@generated|Code generated .* DO NOT EDIT|This file (was|is) (auto-?)?generated|DO NOT EDIT)/i;

export type SkipReason = 'vendor' | 'sensitive' | 'binary' | 'size' | 'noise' | 'generated';

/**
 * Should the indexer read this tree entry? Returns the reason it is skipped, or null. Sensitive names are skipped before
 * anything is read: a skipped file's content never enters the process (docs/design/project-graphs.md section 5, step 1).
 */
export function skipReason(path: string, size: number): SkipReason | null {
  const parts = path.split('/');
  const name = parts[parts.length - 1] ?? path;
  for (const d of parts.slice(0, -1)) {
    if (SENSITIVE_DIRS.has(d.toLowerCase())) return 'sensitive';
  }
  // A folder named `secrets` holds credentials, unless it is a source folder (`src/secrets/redact.ts` is code).
  if (parts.slice(0, -1).some((d) => d.toLowerCase() === 'secrets') && !langOf(path)) return 'sensitive';
  if (looksLikeSecret(path) || SECRET_FIXED.test(name)) {
    if (/^\.env\.(example|sample|template|dist)$/i.test(name)) return 'noise'; // a template holds no values, and is no code
    return 'sensitive';
  }
  if (SECRET_DATA_NAME.test(name) && DATA_EXT.test(name)) return 'sensitive';
  for (const d of parts.slice(0, -1)) if (SKIPPED_DIRS.has(d)) return 'vendor';
  if (NOISE.test(path)) return 'noise';
  if (BINARY_EXT.test(name)) return 'binary';
  if (GENERATED_NAME.test(name)) return 'generated';
  if (size > MAX_FILE_BYTES) return 'size';
  return null;
}

export type Lang = 'typescript' | 'tsx' | 'javascript' | 'python' | 'go' | 'csharp' | 'markdown';

/** The language of a file by extension; null when the graph keeps only a file node (or nothing). */
export function langOf(path: string): Lang | null {
  const m = /\.([A-Za-z0-9]+)$/.exec(path);
  switch (m?.[1]?.toLowerCase()) {
    case 'ts':
    case 'mts':
    case 'cts':
      return 'typescript';
    case 'tsx':
      return 'tsx';
    case 'js':
    case 'mjs':
    case 'cjs':
    case 'jsx':
      return 'javascript';
    case 'py':
      return 'python';
    case 'go':
      return 'go';
    case 'cs':
      return 'csharp';
    case 'md':
    case 'mdx':
      return 'markdown';
    default:
      return null;
  }
}

const TEST_PATH =
  /(^|\/)(tests?|__tests__|spec|specs|e2e|testing)\/|\.(test|spec)\.[cm]?[jt]sx?$|_test\.go$|(^|\/)test_[^/]*\.py$|_test\.py$|[^/]*Tests?\.cs$/i;
export const isTestPath = (path: string): boolean => TEST_PATH.test(path);

/** Package manifests the modules and `depends_on` edges are built from. */
export const isManifest = (path: string): boolean =>
  /(^|\/)(package\.json|go\.mod|pyproject\.toml|setup\.py|Cargo\.toml)$|\.csproj$/.test(path);

/**
 * Splits a `git ls-tree -r -z -l` listing and applies the skip rules. `skipped` counts what was left out and why (the
 * manifest records the counts, never the names).
 */
export function selectFiles(entries: TreeEntry[]): { files: TreeEntry[]; skipped: Record<string, number> } {
  const files: TreeEntry[] = [];
  const skipped: Record<string, number> = {};
  for (const e of entries) {
    const why = skipReason(e.path, e.size);
    if (why) {
      skipped[why] = (skipped[why] ?? 0) + 1;
      continue;
    }
    files.push(e);
  }
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return { files, skipped };
}
