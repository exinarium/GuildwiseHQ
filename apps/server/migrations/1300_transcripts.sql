-- Transcripts of videos and podcasts (feeds and research). The runner fetches a transcript (`aom transcript`), writes it
-- to the vault (`projects/<name>/transcripts/<date>-<slug>.md`) and sends the text here, because the site holds no vault
-- content and the web pages read it from this table. Not a projection: it is written by the runner's rpc, so a rebuild
-- of the projections leaves it alone.
ALTER TABLE digest_items ADD COLUMN transcript jsonb;   -- { status, path?, chars?, autoGenerated? } of video/podcast items

CREATE TABLE transcripts (
  project_id     uuid NOT NULL REFERENCES projects(id),
  url_normalized text NOT NULL,
  url            text NOT NULL,
  title          text NOT NULL,
  language       text,
  auto_generated boolean,
  vault_path     text,
  chars          integer NOT NULL,
  truncated      boolean NOT NULL DEFAULT false,
  text           text NOT NULL,
  created_at     timestamptz NOT NULL,
  PRIMARY KEY (project_id, url_normalized)
);
