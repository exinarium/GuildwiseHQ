const systemBy: DeskActor = { kind: 'system' };

async function actionsOfDay(db: Queryable, orgId: string, now: Date) {
  return rows(
    db,
    `SELECT id, class, action, mode, status, subject_label, reason, inverse IS NOT NULL AS undoable
       FROM ceo_actions WHERE org_id=$1 AND created_at > $2 AND mode IN ('decided','recommended') ORDER BY created_at LIMIT 60`,
    [orgId, new Date(now.getTime() - 86_400_000)],
  );
}

/** The deterministic part of a CEO report when no CEO wrote it (the floor facts plus the CEO's activity). */
export async function renderCeoReportFallback(
  db: Queryable,
  orgId: string,
  digest: FloorDigest,
  now: Date,
): Promise<string> {
  const acts = await actionsOfDay(db, orgId, now);
  const pending = await rows(
    db,
    `SELECT title FROM desk_items WHERE org_id=$1 AND status='open' AND subkind='ceo_recommendation' ORDER BY created_at LIMIT 20`,
    [orgId],
  );
  const out = [
    `# Daily report ${digest.localDate}`,
    '',
    '_Generated by the server: your CEO was not available. Below are the facts._',
    '',
    '## Needs you',
    pending.length ? pending.map((p) => `- ${p.title}`).join('\n') : '- none',
    '',
    '## Decisions the CEO took in the last 24 hours',
    acts
      .filter((a) => a.mode === 'decided')
      .map(
        (a) =>
          `- ${CLASS_LABEL[a.class as ActionClass] ?? a.class}: ${a.subject_label}${a.status === 'undone' ? ' (undone)' : ''}`,
      )
      .join('\n') || '- none',
    '',
    renderFloorReportFallback(digest).replace(/^# .*\n/, ''),
  ];
  const repeats = await listOpenRepeats(db, orgId);
  if (repeats.length)
    out.push(
      '',
      '## Things you keep asking me',
      ...repeats.map(
        (r) =>
          `- ${r.key}: ${r.count7} times in 7 days, ${r.count30} in 30 days. Suggestion: make it a ${r.suggestion}.`,
      ),
    );
  out.push(...(await topicsReportLines(db, orgId, now)));
  return out.join('\n');
}

/**
 * Posts the daily report: the `alert/ceo_report` desk item (with the digest, the CEO's actions and the training scores
 * in `data`), the signals it reports, the e-mail, and `CeoReportPosted`. `fallback`: the server wrote it.
 */
export async function postCeoReport(
  ctx: Ctx,
  db: Queryable,
  orgId: string,
  input: {
    report: string;
    localDate: string;
    fallback: boolean;
    batchId?: string | undefined;
    agentId?: string | undefined;
    tx?: Tx | undefined;
  },
): Promise<void> {
  const now = ctx.clock.now();
  const digest = await buildFloorDigest(db, orgId, now, input.localDate);
  const thread = await ensureCeoThread(db, orgId);
  const acts = await actionsOfDay(db, orgId, now);
  // Repeated off-board jobs (4+ in 7 days, 10+ in 30): found now if the job log has not raised them yet, listed in the report.
  const found = await detectRepeats(db, orgId, now);
  if (found.length) await ctx.store.append(found, input.tx ? { tx: input.tx } : {});
  const repeats = await listOpenRepeats(db, orgId);
  const orderTurns = await listOrderTurns(db, orgId, { since: new Date(now.getTime() - 86_400_000) });
  const scores = agreementScores(
    await rows<{ class: string; response: any }>(
      db,
      `SELECT class, response FROM ceo_actions WHERE org_id=$1 AND mode='recommended' AND response IS NOT NULL`,
      [orgId],
    ),
  );
  const deskItemId = randomUUID();
  const by: DeskActor = input.agentId ? { kind: 'agent', agentId: input.agentId, role: 'ceo' } : systemBy;
  const facts = renderFloorReportFallback(digest).replace(/^# .*\n/, '## The facts behind this report\n');
  // What the CEO itself cost in the last day, by model (the model switch makes this worth a line).
  const byModel = await rows(
    db,
    `SELECT model, round(sum(cost_usd_micros)/1e6, 2) AS usd, count(*)::int AS turns FROM shift_costs
      WHERE org_id=$1 AND kind IN ('ceo','ceo_chat') AND ended_at > $2 GROUP BY model ORDER BY sum(cost_usd_micros) DESC`,
    [orgId, new Date(now.getTime() - 86_400_000)],
  );
  const spendLine = byModel.length
    ? `\n\n## What the CEO cost, by model (last 24 hours)\n${byModel.map((m) => `- ${m.model}: $${m.usd} (${m.turns} ${m.turns === 1 ? 'turn' : 'turns'})`).join('\n')}`
    : '';
  // Research topics: the proposals waiting for the owner and what was published from his topics (the web page shows them live
  // with Accept / Edit / Reject; the fallback report already carries the text).
  const topicsText = input.fallback ? '' : (await topicsReportLines(db, orgId, now)).join('\n');
  // Agent suggestions added to project backlogs since the last report: a notice section, left out when there are none.
  const suggestions = await unreportedSuggestions(db, orgId);
  const backlogText = backlogNoticeLines(suggestions.rows, suggestions.more).join('\n');
  const body = `${input.report.trim()}${topicsText ? `\n${topicsText}` : ''}${backlogText}\n\n---\n${facts}${spendLine}`;
  const open = digest.signals.filter((s) => s.status === 'open');
  const events: AppendInput[] = [
    ...thread.events,
    {
      streamId: streamId.desk(deskItemId),
      event: {
        type: 'DeskItemCreated',
        payload: {
          deskItemId,
          kind: 'alert',
          subkind: 'ceo_report',
          title: `Daily report ${input.localDate}`,
          body,
          options: [],
          blocking: false,
          pinned: false,
          affectedCardIds: [],
          askedBy: by,
          ...(thread.threadId ? { chatThreadId: thread.threadId } : {}),
          data: {
            digest,
            fallback: input.fallback,
            ...(suggestions.rows.length
              ? {
                  backlogSuggestions: suggestions.rows.map((s) => ({
                    itemId: s.id,
                    projectKey: s.projectKey,
                    title: s.title,
                    priority: s.priority,
                    agentName: s.agentName,
                    cardRef: s.cardRef,
                  })),
                }
              : {}),
            ceo: {
              actions: acts.map((a) => ({
                id: a.id,
                class: a.class,
                mode: a.mode,
                status: a.status,
                subject: a.subject_label,
                undoable: a.undoable,
                correctable: a.mode === 'decided',
              })),
              repeats,
              orderTurns,
              scores,
              totals: sumScores(scores),
            },
          },
        },
      },
      actor: input.agentId ? agentActor(input.agentId) : SYSTEM_ACTOR,
      scope: orgScope(orgId),
    },
    {
      streamId: streamId.ceo(orgId),
      event: {
        type: 'CeoReportPosted',
        payload: {
          orgId,
          localDate: input.localDate,
          deskItemId,
          fallback: input.fallback,
          ...(input.batchId ? { batchId: input.batchId } : {}),
        },
      },
      actor: input.agentId ? agentActor(input.agentId) : SYSTEM_ACTOR,
      scope: orgScope(orgId),
    },
    ...(suggestions.rows.length
      ? [
          {
            streamId: streamId.ceo(orgId),
            event: {
              type: 'BacklogSuggestionsReported',
              payload: { orgId, deskItemId, itemIds: suggestions.rows.map((s) => s.id) },
            },
            actor: SYSTEM_ACTOR,
            scope: orgScope(orgId),
          } satisfies AppendInput,
        ]
      : []),
    ...open.map(
      (s): AppendInput => ({
        streamId: streamId.baSignal(s.id),
        event: { type: 'BaSignalReported', payload: { signalId: s.id, deskItemId } },
        actor: SYSTEM_ACTOR,
        scope: orgScope(orgId),
      }),
    ),
  ];
  await ctx.store.append(events, input.tx ? { tx: input.tx } : {});
  // The mail goes out after the append (a failing mail never blocks the report).
  void sendReportMail(
    ctx,
    orgId,
    `${input.report}${backlogText ? `\n${backlogText}` : ''}`,
    input.localDate,
    input.fallback,
  ).catch((err) => ctx.log.error({ err }, 'ceo report mail failed'));
}

async function sendReportMail(
  ctx: Ctx,
  orgId: string,
  report: string,
  localDate: string,
  fallback: boolean,
): Promise<void> {
  const ceo = await loadCeo(ctx.pool, orgId);
  const ownerId = await orgOwnerId(ctx.pool, orgId);
  const u = await one(ctx.pool, 'SELECT email, display_name FROM users WHERE id=$1', [ownerId]);
  if (!u?.email) return;
  const name = ceo?.agentId
    ? ((await one(ctx.pool, 'SELECT name FROM agents WHERE id=$1', [ceo.agentId]))?.name ?? 'Your CEO')
    : 'Your CEO';
  await ctx.mailer.send({
    ...ceoReportMail({
      to: u.email,
      name: u.display_name,
      origin: ctx.config.publicOrigin,
      ceoName: name,
      localDate,
      report,
      fallback,
    }),
    orgId,
  });
}

/** Terminal and non-terminal reports of a `ceo` shift (`aom ceo done|report`, `aom comment`). */
export async function applyCeoReport(
  ctx: Ctx,
  tx: Tx,
  _ws: WsRef,
  msg: RunnerToServerOf<'shift.report'>,
  shift: Row,
): Promise<ReportResult> {
  const batch = await one(tx, 'SELECT * FROM ceo_batches WHERE shift_id=$1 FOR UPDATE', [shift.id]);
  const report = msg.report;
  if (!batch || batch.status !== 'running')
    return {
      accepted: false,
      error: 'this shift is no longer open; there is nothing left to do. Finish now.',
    };
  if (report.kind === 'comment') return { accepted: true };
  if (report.kind !== 'outcome')
    return {
      accepted: false,
      error:
        'there are no questions in a background task: use `aom ceo notify` or `aom ceo recommend` to reach the owner',
    };
  const review = batch.purpose === 'review';
  const expected = review ? CEO_OUTCOME.report : CEO_OUTCOME.done;
  if (report.outcomeId !== expected)
    return {
      accepted: false,
      error: `outcome '${report.outcomeId}' is not available (allowed: ${expected})`,
    };
  const now = ctx.clock.now();
  if (review) {
    const data = CeoReportDataSchema.safeParse(report.data);
    if (!data.success) return { accepted: false, error: `invalid report data: ${data.error.message}` };
    await postCeoReport(ctx, tx, batch.org_id, {
      report: data.data.report,
      localDate: batch.local_date ?? localParts(now, null).date,
      fallback: false,
      batchId: batch.id,
      agentId: shift.agent_id,
      tx,
    });
  } else {
    const data = CeoDoneDataSchema.safeParse(report.data);
    if (!data.success) return { accepted: false, error: `invalid data: ${data.error.message}` };
    await exec(tx, 'UPDATE ceo_batches SET summary=$2 WHERE id=$1', [batch.id, data.data.summary]);
  }
  await exec(tx, `UPDATE ceo_batches SET status='done', updated_at=$2 WHERE id=$1`, [batch.id, now]);
  await exec(tx, `UPDATE ceo_wakes SET status='done', done_at=$2 WHERE batch_id=$1`, [batch.id, now]);
  return { accepted: true };
}

/** A review nobody wrote in time (or that failed twice) is posted by the server. */
export async function postFallbackReview(
  ctx: Ctx,
  orgId: string,
  localDate: string,
  wakeIds: string[],
): Promise<void> {
  const now = ctx.clock.now();
  // Repeats are found before the text is written, so the template lists them too.
  const found = await detectRepeats(ctx.pool, orgId, now);
  if (found.length) await ctx.store.append(found);
  const digest = await buildFloorDigest(ctx.pool, orgId, now, localDate);
  const text = await renderCeoReportFallback(ctx.pool, orgId, digest, now);
  await postCeoReport(ctx, ctx.pool, orgId, { report: text, localDate, fallback: true });
  await exec(ctx.pool, `UPDATE ceo_wakes SET status='done', done_at=$2 WHERE id = ANY($1::uuid[])`, [
    wakeIds,
    now,
  ]);
}

/** Queues the day's review once the owner's local clock passes the report time (per organization with an active CEO). */
export async function reportTimeFor(ctx: Ctx, orgId: string) {
  const ceo = await loadCeo(ctx.pool, orgId);
  const prefs = await reportingOf(ctx.pool, orgId);
  return { ceo, prefs, at: ceo?.settings.reportAt ?? prefs.dailyAt };
}
