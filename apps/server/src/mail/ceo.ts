import { type MailBlock, brandedMail } from './layout.ts';
import type { MailMessage } from './mailer.ts';

/** Mails of the CEO to its owner: an immediate notification and the daily report (docs/design/ceo-agent-v2.md section 6). */

const KIND_HEADING = {
  needs_you: 'Your CEO needs you',
  urgent: 'Urgent: your CEO needs to tell you something',
  task_done: 'A task you gave your CEO is done',
} as const;

export function ceoNotifyMail(opts: {
  to: string;
  origin: string;
  ceoName: string;
  kind: keyof typeof KIND_HEADING;
  title: string;
  text: string;
  deskUrlPath?: string;
}): MailMessage {
  const body: MailBlock[] = [{ quote: opts.text }];
  return brandedMail({
    to: opts.to,
    subject: `${opts.ceoName}: ${opts.title}`,
    preheader: opts.text.slice(0, 120),
    heading: KIND_HEADING[opts.kind],
    origin: opts.origin,
    body,
    cta: { label: 'Open the desk', url: `${opts.origin.replace(/\/+$/, '')}${opts.deskUrlPath ?? '/desk'}` },
    note: `From ${opts.ceoName}, your CEO. Notification settings are on the CEO page.`,
  });
}

export function ceoReportMail(opts: {
  to: string;
  name: string;
  origin: string;
  ceoName: string;
  localDate: string;
  report: string;
  fallback: boolean;
}): MailMessage {
  const body: MailBlock[] = [
    `Good morning ${opts.name || ''}. Here is the daily report of ${opts.localDate}.`.replace(' .', '.'),
    ...(opts.fallback ? [{ small: 'Generated by the server: your CEO was not available.' } as MailBlock] : []),
    { quote: opts.report.length > 6000 ? `${opts.report.slice(0, 6000)}\n[...cut: open the desk for the rest]` : opts.report },
  ];
  return brandedMail({
    to: opts.to,
    subject: `${opts.ceoName}: daily report ${opts.localDate}`,
    preheader: 'What needs you, what was decided, issues and budget.',
    heading: 'Daily report',
    origin: opts.origin,
    body,
    cta: { label: 'Open the desk', url: `${opts.origin.replace(/\/+$/, '')}/desk` },
  });
}
