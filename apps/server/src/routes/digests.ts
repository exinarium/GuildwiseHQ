import {
  DigestItemsQuerySchema,
  IdParamsSchema,
  RateDigestItemRequestSchema,
  TranscriptQuerySchema,
} from '@aom/shared';
import type { FastifyInstance } from 'fastify';
import { requireUser } from '../auth/guards.ts';
import { loadVisibleProject } from '../authz/scope.ts';
import { rateDigestItem } from '../commands/digests.ts';
import { transcriptFor } from '../commands/transcripts.ts';
import type { Ctx } from '../context.ts';
import { HttpError } from '../errors.ts';
import { listDigestItems } from '../queries/digests.ts';
import { typed } from './util.ts';

export function digestRoutes(ctx: Ctx) {
  return async (fastify: FastifyInstance) => {
    const app = typed(fastify);

    app.get('/api/digest-items', { schema: { querystring: DigestItemsQuerySchema } }, async (req) => {
      const s = await requireUser(ctx, req);
      return { items: await listDigestItems(ctx.pool, s.user.id, req.query) };
    });

    app.post(
      '/api/digest-items/:id/rate',
      { schema: { params: IdParamsSchema, body: RateDigestItemRequestSchema } },
      async (req) => {
        const s = await requireUser(ctx, req);
        return rateDigestItem(ctx, s.user, req.params.id, req.body);
      },
    );

    app.get(
      '/api/projects/:id/transcript',
      { schema: { params: IdParamsSchema, querystring: TranscriptQuerySchema } },
      async (req) => {
        const s = await requireUser(ctx, req);
        const project = await loadVisibleProject(ctx.pool, s.user.id, req.params.id, { allowInterest: true });
        const t = await transcriptFor(ctx.pool, project.id, req.query.url);
        if (!t) throw new HttpError(404, 'not_found', 'no transcript available');
        return {
          url: t.url,
          title: t.title,
          language: t.language,
          autoGenerated: t.auto_generated,
          path: t.vault_path,
          text: t.text,
          truncated: t.truncated,
        };
      },
    );
  };
}
