import { useState } from 'react';
import { ApiError } from '../api/client.ts';
import { useTranscript } from '../api/queries/digest.ts';
import { Spinner } from './ui.tsx';

/**
 * "Transcript" expander of a video or podcast: the text is read from the site only when opened. `available: false`
 * (the scout found none) shows `No transcript available` without asking.
 */
export function TranscriptExpander({
  projectId,
  url,
  available,
  label = 'Transcript',
}: {
  projectId: string;
  url: string;
  available: boolean;
  label?: string;
}) {
  const [open, setOpen] = useState(false);
  if (!available)
    return (
      <p className="mt-1 text-xs text-zinc-500" data-testid="transcript-none">
        No transcript available
      </p>
    );
  return (
    <div className="mt-1" data-testid="transcript">
      <button
        type="button"
        aria-expanded={open}
        onClick={() => setOpen((o) => !o)}
        className="text-xs font-medium underline"
      >
        {open ? `Hide ${label.toLowerCase()}` : label}
      </button>
      {open && <TranscriptText projectId={projectId} url={url} />}
    </div>
  );
}

function TranscriptText({ projectId, url }: { projectId: string; url: string }) {
  const t = useTranscript(projectId, url, true);
  if (t.isPending) return <Spinner label="Loading transcript" />;
  if (t.error) {
    const missing = t.error instanceof ApiError && t.error.status === 404;
    return (
      <p className="mt-1 text-xs text-zinc-500" data-testid="transcript-none">
        {missing ? 'No transcript available' : 'Could not load the transcript'}
      </p>
    );
  }
  return (
    <div className="mt-1">
      <p className="text-xs text-zinc-500" data-testid="transcript-meta">
        {t.data.language ?? 'language unknown'}
        {t.data.autoGenerated ? ' · auto-generated captions' : ''}
        {t.data.truncated ? ' · truncated' : ''}
        {t.data.path ? ` · ${t.data.path}` : ''}
      </p>
      <pre
        className="mt-1 max-h-96 overflow-y-auto rounded-md bg-zinc-50 p-2 text-xs whitespace-pre-wrap dark:bg-zinc-950"
        data-testid="transcript-text"
      >
        {t.data.text}
      </pre>
    </div>
  );
}
