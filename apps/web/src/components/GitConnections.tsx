import {
  CONNECTABLE_FORGES,
  type ConnectableForge,
  connectCommand,
  connectSteps,
  FORGE_LABELS,
  GIT_ACCESS_LABELS,
  type GitAccessMethod,
  type GitConnection,
  SSH_CHECK_LABELS,
  type SshKeyMode,
  sshUploadHelp,
  type WorkstationDto,
} from '@aom/shared';
import { useState } from 'react';
import { useGitSsh, useRecheckGit } from '../api/queries/forges.ts';
import { copyText } from '../lib/secure.ts';
import { Badge, Button, ErrorBox, TextInput, useToast } from './ui.tsx';

/** The connection of a workstation to a provider (the best one when several hosts are reported). */
export function connectionOf(
  w: Pick<WorkstationDto, 'git'> | undefined,
  provider: ConnectableForge,
): GitConnection | undefined {
  const list = (w?.git?.connections ?? []).filter((c) => c.provider === provider);
  return list.find((c) => c.state === 'connected') ?? list[0];
}

export function ConnectionBadge({ c }: { c: GitConnection | undefined }) {
  if (!c) return <Badge title="Not reported yet">Unknown</Badge>;
  if (c.state === 'connected')
    return (
      <Badge tone="green" {...(c.detail ? { title: c.detail } : {})}>
        {c.account ? `Connected as ${c.account}` : 'Connected'}
      </Badge>
    );
  if (c.problem === 'unreachable')
    return (
      <Badge tone="amber" {...(c.detail ? { title: c.detail } : {})}>
        Could not check
      </Badge>
    );
  if (c.state === 'unavailable') return <Badge tone="amber">Tool missing</Badge>;
  if (c.problem === 'token_refused')
    return (
      <Badge tone="amber" {...(c.detail ? { title: c.detail } : {})}>
        Token refused
      </Badge>
    );
  return (
    <Badge tone="neutral" {...(c.detail ? { title: c.detail } : {})}>
      Not connected
    </Badge>
  );
}

/**
 * The "Connect" helper: the steps and the one command to run on the workstation. Credentials are entered there and
 * stay there; this page only learns whether it worked ("Check again").
 */
export function ConnectHelper({
  provider,
  workstationId,
  host,
}: {
  provider: ConnectableForge;
  workstationId: string;
  host?: string;
}) {
  const toast = useToast();
  const recheck = useRecheckGit();
  const cmd = connectCommand(provider);
  return (
    <div
      className="mt-2 rounded-control border border-line bg-sunken p-3 text-sm"
      data-testid={`connect-${provider}`}
    >
      <p className="mb-2 font-medium text-fg">Connect {FORGE_LABELS[provider]} on this workstation</p>
      <p className="mb-2 text-muted">
        Run this in a terminal on the workstation. Your login or token stays on that machine; the server only
        learns whether it is connected. The DevOps engineer can walk you through it in chat.
      </p>
      <div className="mb-2 flex flex-wrap items-center gap-2">
        <code className="rounded bg-surface px-2 py-1 font-mono text-xs break-all">{cmd}</code>
        <Button
          size="sm"
          variant="secondary"
          onClick={async () => {
            if (await copyText(cmd)) toast.success('Command copied');
          }}
        >
          Copy
        </Button>
      </div>
      <ol className="mb-3 list-none space-y-1 text-muted">
        {connectSteps(provider, host).map((s) => (
          <li key={s}>{s}</li>
        ))}
      </ol>
      <Button size="sm" onClick={() => recheck.mutate(workstationId)} loading={recheck.isPending}>
        Check again
      </Button>
      {recheck.isSuccess && (
        <span className="ml-2 text-xs text-subtle">Asked the workstation; this updates in a moment.</span>
      )}
      <ErrorBox error={recheck.error} />
    </div>
  );
}

/**
 * SSH instead of an API token for one git host: the default access method of this workstation, the key (generated by
 * the runner and shown here as a PUBLIC key to add on the host, a key file of your own, or the ssh-agent) and a check
 * with a clear state. Private keys never leave the workstation; this page only sees paths, the public key and the result.
 */
export function SshPanel({
  w,
  provider,
  c,
}: {
  w: WorkstationDto;
  provider: ConnectableForge;
  c: GitConnection | undefined;
}) {
  const toast = useToast();
  const run = useGitSsh();
  const ssh = c?.ssh;
  const host = c?.host;
  const [method, setMethod] = useState<GitAccessMethod>(ssh?.defaultMethod ?? 'https');
  const [key, setKey] = useState<SshKeyMode>(ssh?.key ?? 'generated');
  const [keyPath, setKeyPath] = useState(ssh?.key === 'path' ? (ssh.keyPath ?? '') : '');
  const [repoUrl, setRepoUrl] = useState('');
  const base = { workstationId: w.id, provider, ...(host ? { host } : {}) };
  const check = ssh?.check;
  const cmd = `aom-runner git-connect ${provider} --ssh`;
  const keyOk = key !== 'path' || keyPath.trim().length > 0;
  return (
    <div
      className="mt-2 rounded-control border border-line bg-sunken p-3 text-sm"
      data-testid={`ssh-${provider}`}
    >
      <p className="mb-1 font-medium text-fg">SSH for {FORGE_LABELS[provider]} on this workstation</p>
      <p className="mb-3 text-muted">
        Use an SSH key instead of an API token for clone, fetch and push. The key stays on the workstation.
        Pull requests, branch rules and the repository list still need the API token or CLI login; without
        them the branch is pushed and the manager opens the pull request.
      </p>
      <div className="mb-3 flex flex-wrap items-end gap-3">
        <label className="flex flex-col gap-1 text-xs text-subtle">
          Default for new clones
          <select
            aria-label={`Default access method for ${FORGE_LABELS[provider]}`}
            className="h-9 rounded-control border border-control bg-surface px-2 text-sm text-fg"
            value={method}
            onChange={(e) => setMethod(e.target.value as GitAccessMethod)}
          >
            <option value="https">{GIT_ACCESS_LABELS.https}</option>
            <option value="ssh">{GIT_ACCESS_LABELS.ssh}</option>
          </select>
        </label>
        <label className="flex flex-col gap-1 text-xs text-subtle">
          Key
          <select
            aria-label={`SSH key of ${FORGE_LABELS[provider]}`}
            className="h-9 rounded-control border border-control bg-surface px-2 text-sm text-fg"
            value={key}
            onChange={(e) => setKey(e.target.value as SshKeyMode)}
          >
            <option value="generated">A key made by the runner</option>
            <option value="path">A key file I already have</option>
            <option value="agent">My ssh-agent / ~/.ssh/config</option>
          </select>
        </label>
        {key === 'path' && (
          <TextInput
            label="Private key file on the workstation"
            hint="Written out in full, like /home/you/.ssh/id_ed25519"
            value={keyPath}
            onChange={(e) => setKeyPath(e.target.value)}
          />
        )}
        <Button
          size="sm"
          variant="primary"
          disabled={!w.connected || !keyOk}
          loading={run.isPending}
          onClick={() =>
            run.mutate(
              {
                ...base,
                action: key === 'generated' ? 'prepare' : 'save',
                defaultMethod: method,
                key,
                ...(key === 'path' ? { keyPath: keyPath.trim() } : {}),
              },
              { onSuccess: () => toast.success('Asked the workstation; this updates in a moment') },
            )
          }
        >
          {key === 'generated' ? 'Save and create key' : 'Save'}
        </Button>
      </div>
      {ssh?.publicKey && (
        <div className="mb-3" data-testid={`ssh-public-key-${provider}`}>
          <p className="mb-1 text-xs font-medium text-subtle">
            Public key: add it to your {FORGE_LABELS[provider]} account
          </p>
          <div className="flex flex-wrap items-start gap-2">
            <code className="min-w-0 flex-1 rounded bg-surface px-2 py-1 font-mono text-xs break-all">
              {ssh.publicKey}
            </code>
            <Button
              size="sm"
              variant="secondary"
              onClick={async () => {
                if (await copyText(ssh.publicKey ?? '')) toast.success('Public key copied');
              }}
            >
              Copy
            </Button>
          </div>
          <p className="mt-1 text-xs text-muted">{sshUploadHelp(provider, host)}</p>
        </div>
      )}
      <div className="flex flex-wrap items-end gap-2">
        <TextInput
          label="Check against a repository (optional)"
          hint="Paste a repository URL to test with the real thing; empty tests the connection to the host"
          value={repoUrl}
          onChange={(e) => setRepoUrl(e.target.value)}
        />
        <Button
          size="sm"
          variant="secondary"
          disabled={!w.connected}
          loading={run.isPending}
          onClick={() =>
            run.mutate({
              ...base,
              action: 'check',
              ...(repoUrl.trim() ? { repoUrl: repoUrl.trim() } : {}),
            })
          }
        >
          Check SSH
        </Button>
        {check ? (
          <Badge
            tone={check.state === 'ok' ? 'green' : 'amber'}
            {...(check.detail ? { title: check.detail } : {})}
          >
            {SSH_CHECK_LABELS[check.state]}
          </Badge>
        ) : (
          <Badge>Not checked</Badge>
        )}
      </div>
      {check && check.state !== 'ok' && check.detail && (
        <p className="mt-1 text-xs text-subtle" data-testid={`ssh-detail-${provider}`}>
          {check.detail}
        </p>
      )}
      <p className="mt-3 text-xs text-subtle">
        Prefer the terminal? Run <code className="font-mono">{cmd}</code> on the workstation (add{' '}
        <code className="font-mono">--key-file &lt;path&gt;</code> or{' '}
        <code className="font-mono">--agent</code>, and <code className="font-mono">--check</code> to test).
      </p>
      <ErrorBox error={run.error} />
    </div>
  );
}

/** One row per provider on the Workstations page, each with a Connect helper when it is not connected. */
export function GitConnectionsPanel({ w }: { w: WorkstationDto }) {
  const [open, setOpen] = useState<ConnectableForge | null>(null);
  const [sshOpen, setSshOpen] = useState<ConnectableForge | null>(null);
  return (
    <div className="mt-4 border-t border-line pt-3 text-sm" data-testid="git-connections">
      <p className="mb-2 text-xs font-medium text-subtle">Git hosts</p>
      {!w.git || w.git.connections.length === 0 ? (
        <p className="text-subtle">
          Not reported yet (needs a current runner). Run{' '}
          <code className="font-mono text-xs">aom-runner git-connect github</code> to set one up.
        </p>
      ) : null}
      <ul className="flex flex-col gap-2">
        {CONNECTABLE_FORGES.map((p) => {
          const c = connectionOf(w, p);
          return (
            <li key={p} data-testid={`git-${p}`}>
              <div className="flex flex-wrap items-center gap-2">
                <span className="w-40 font-medium text-fg">{FORGE_LABELS[p]}</span>
                <ConnectionBadge c={c} />
                {c?.host &&
                  c.host !== 'github.com' &&
                  c.host !== 'gitlab.com' &&
                  c.host !== 'bitbucket.org' &&
                  c.host !== 'dev.azure.com' && (
                    <span className="font-mono text-xs text-subtle">{c.host}</span>
                  )}
                {c?.state !== 'connected' && w.connected && (
                  <Button size="sm" variant="secondary" onClick={() => setOpen(open === p ? null : p)}>
                    {open === p ? 'Hide' : 'Connect'}
                  </Button>
                )}
                {c?.ssh && (
                  <Badge
                    tone={c.ssh.defaultMethod === 'ssh' ? 'blue' : 'neutral'}
                    title="The default for new clones on this workstation"
                  >
                    {c.ssh.defaultMethod === 'ssh' ? 'Default: SSH' : 'Default: token / CLI'}
                  </Badge>
                )}
                {w.connected && (
                  <Button size="sm" variant="ghost" onClick={() => setSshOpen(sshOpen === p ? null : p)}>
                    {sshOpen === p ? 'Hide SSH' : 'SSH'}
                  </Button>
                )}
              </div>
              {sshOpen === p && <SshPanel w={w} provider={p} c={c} />}
              {open === p && (
                <ConnectHelper provider={p} workstationId={w.id} {...(c?.host ? { host: c.host } : {})} />
              )}
            </li>
          );
        })}
      </ul>
    </div>
  );
}
