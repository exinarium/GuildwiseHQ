import { describe, expect, it } from 'vitest';
import {
  CommitAsSchema,
  checkOutboundLeaks,
  FinalizeExecutePayloadSchema,
  NO_COMMIT_IDENTITY_MESSAGE,
  RepoReportSchema,
  SetCommitAsRequestSchema,
} from '../src/index.ts';

describe('Commit as (backlog #65)', () => {
  it('accepts a name and a well-formed e-mail, trimmed', () => {
    expect(CommitAsSchema.parse({ name: ' Pieter Jordaan ', email: ' pieter@example.com ' })).toEqual({
      name: 'Pieter Jordaan',
      email: 'pieter@example.com',
    });
  });

  it('rejects an empty name and malformed e-mails', () => {
    for (const email of ['x', 'x@', '@x.y', 'a b@x.y', 'a@x', 'a@@x.y', '<a@x.y>'])
      expect(CommitAsSchema.safeParse({ name: 'P', email }).success, email).toBe(false);
    expect(CommitAsSchema.safeParse({ name: '  ', email: 'a@x.y' }).success).toBe(false);
  });

  it('null clears the setting', () => {
    expect(SetCommitAsRequestSchema.parse({ commitAs: null })).toEqual({ commitAs: null });
  });

  it('protocol fields are additive: old payloads and reports still parse', () => {
    expect(
      RepoReportSchema.parse({ remoteUrl: 'u', localPath: '/p', headBranch: 'main' }).identity,
    ).toBeUndefined();
    expect(
      RepoReportSchema.parse({
        remoteUrl: 'u',
        localPath: '/p',
        headBranch: 'main',
        identity: { name: 'A', email: 'a@x.y', source: 'repo' },
      }).identity,
    ).toEqual({ name: 'A', email: 'a@x.y', source: 'repo' });
    const base = {
      cardId: '019e3f6a-7b1c-7a2d-8c3e-0123456789a1',
      ref: 'TOY-1',
      title: 't',
      projectKey: 'TOY',
      action: 'merge',
      repoId: '019e3f6a-7b1c-7a2d-8c3e-0123456789a2',
      remoteUrlNormalized: 'x',
      baseBranch: 'main',
      branchName: 'b',
      worktreePath: null,
    };
    expect(FinalizeExecutePayloadSchema.parse(base).commitAs).toBeUndefined();
    expect(
      FinalizeExecutePayloadSchema.parse({ ...base, commitAs: { name: 'A', email: 'a@x.y' } }).commitAs,
    ).toEqual({ name: 'A', email: 'a@x.y' });
  });

  it('the refusal names the three places and no product', () => {
    expect(NO_COMMIT_IDENTITY_MESSAGE).toMatch(/Project settings > Commit as/);
    expect(NO_COMMIT_IDENTITY_MESSAGE).toMatch(/in the repository/);
    expect(NO_COMMIT_IDENTITY_MESSAGE).toMatch(/--global/);
    expect(NO_COMMIT_IDENTITY_MESSAGE).not.toMatch(/guildwise|aom/i);
  });
});

describe('outgoing text: invisible organisation markers', () => {
  const bad = [
    'Fixed by our AI agent overnight.',
    'Written with Claude.',
    'See https://app.guildwisehq.com/cards/1',
    'Generated by Guildwise HQ',
    'This came from card P4-12.',
    'The builder Ada did this',
  ];
  it.each(bad)('refuses %s', (text) => {
    expect(checkOutboundLeaks(text, ['Ada']).ok).toBe(false);
  });
  it('lets a plain human update through', () => {
    expect(checkOutboundLeaks('Fixed the login redirect in DCPL-4276; it is on the test site now.').ok).toBe(
      true,
    );
  });
});
