const TRACKING_PARAM = /^(utm_.*|fbclid|gclid|mc_cid|mc_eid|igshid|ref|ref_src|si|feature)$/i;

/** Canonical form of a URL for the seen-list: no scheme, `www.`, fragment, tracking params, default port or trailing slash. */
export function normalizeUrl(raw: string): string {
  let u: URL;
  try {
    u = new URL(raw.trim());
  } catch {
    return raw.trim().toLowerCase();
  }
  const host = u.hostname.toLowerCase().replace(/^www\./, '');
  const port = u.port && u.port !== '80' && u.port !== '443' ? `:${u.port}` : '';
  const path = u.pathname.replace(/\/+$/, '');
  const params = [...u.searchParams.entries()]
    .filter(([k]) => !TRACKING_PARAM.test(k))
    .sort(([a, av], [b, bv]) => (a === b ? av.localeCompare(bv) : a.localeCompare(b)));
  const query = params.length ? `?${params.map(([k, v]) => `${k}=${v}`).join('&')}` : '';
  return `${host}${port}${path}${query}`;
}

const STOP = new Set([
  'the',
  'a',
  'an',
  'of',
  'and',
  'to',
  'in',
  'on',
  'for',
  'is',
  'at',
  'with',
  'by',
  'new',
]);

/** Words of a title that identify the story (lowercase, no punctuation, no filler words). */
export function titleTokens(title: string): string[] {
  return title
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, ' ')
    .split(' ')
    .filter((w) => (w.length > 1 || /\d/.test(w)) && !STOP.has(w));
}

/**
 * The same story from another source: identical titles, or titles that share at least 80 percent of their words
 * (Jaccard, with at least three words in common so short titles cannot collide by accident).
 */
export function isSameStory(a: string, b: string): boolean {
  const x = new Set(titleTokens(a));
  const y = new Set(titleTokens(b));
  if (x.size === 0 || y.size === 0) return false;
  const shared = [...x].filter((w) => y.has(w)).length;
  if (shared === x.size && shared === y.size) return true;
  const union = x.size + y.size - shared;
  return shared >= 3 && shared / union >= 0.8;
}

/** Picks the first `max` items in the order given (the agent's best first), whatever their kind. */
export function applyMaxItems<T>(items: readonly T[], max: number): { kept: T[]; dropped: T[] } {
  return { kept: items.slice(0, Math.max(0, max)), dropped: items.slice(Math.max(0, max)) };
}

export const FEED_LIST_HEADER = '# Feed\n\nRunning list, oldest first. Entries are only ever appended.\n\n';

/** ` Transcript: [file](transcripts/...)`, relative to `feed.md` (which sits next to the `transcripts/` folder). */
function transcriptLink(t: TranscriptRef | undefined): string {
  if (t?.status !== 'ok' || !t.path) return '';
  const at = t.path.indexOf('/transcripts/');
  return ` Transcript: [transcript](${at === -1 ? t.path : t.path.slice(at + 1)})`;
}

/** One line per item, appended to `projects/<name>/feed.md` (never rewritten; oldest first, newest last). */
export function renderFeedEntries(
  items: ReadonlyArray<
    Pick<DigestItem, 'kind' | 'url' | 'title' | 'source' | 'publishedAt' | 'summary'> &
      Partial<Pick<DigestItem, 'transcript'>>
  >,
  loggedAt: Date,
): string {
  const logged = loggedAt.toISOString().slice(0, 10);
  return `${items
    .map(
      (i) =>
        `- ${logged} [${i.title.replace(/[[\]]/g, '')}](${i.url}) (${i.kind}, ${i.source}, published ${i.publishedAt.slice(0, 10)}): ${i.summary.replace(/\s+/g, ' ').trim()}${transcriptLink(i.transcript)}`,
    )
    .join('\n')}\n`;
}

export const TASTE_HEADER =
  "# Taste\n\nRules and examples from the manager's ratings, one per line. Curators read this before filtering; edit or delete lines freely.\n\n";

const VERDICT_RULE: Record<FeedVerdict, string> = {
  useful: 'Prefer',
  irrelevant: 'Skip',
  boring: 'Deprioritise',
};

export interface TasteEntryInput {
  verdict: FeedVerdict;
  kind: string;
  title: string;
  source: string;
  url: string;
  reason?: string | null | undefined;
}

/** An explicit, readable rule plus the example it came from (never a score). */
export function renderTasteEntry(e: TasteEntryInput): string {
  const why = e.reason?.trim() ? ` Reason: ${e.reason.replace(/\s+/g, ' ').trim()}.` : '';
  return `- ${VERDICT_RULE[e.verdict]} ${e.kind}s like "${e.title.replace(/"/g, "'")}" from ${e.source} (rated ${e.verdict}).${why} Example: ${e.url}\n`;
}

/** A rule the manager approved after a curator proposed it. */
export function renderTasteRule(rule: string): string {
  return `- Rule: ${rule.replace(/\s+/g, ' ').trim()}\n`;
}

/** Titles the taste file says to skip (`Skip ... like "<title>"`), for agents that apply the rules mechanically. */
export function tasteSkipTitles(taste: string): string[] {
  const out: string[] = [];
  for (const m of taste.matchAll(/^- Skip \S+ like "([^"]+)"/gm)) out.push(m[1] as string);
  return out;
}

// ------------------------------------------------------------------ explicit taste rules (docs/design/interests.md)

/** One explicit rule of a feed project, as the site stores it (`taste_seeds.rules`). `interestId` limits it to that interest's cards. */
export interface TasteSeedLine {
  text: string;
  interestId: string | null;
}

export const TASTE_SEED_SECTION_ID = 'seed';
const sectionBegin = (id: string, version: number): string =>
  `<!-- aom:section ${id} v=${version} begin. Managed on the site (Interests page); edits here are overwritten. -->`;
const sectionEnd = (id: string): string => `<!-- aom:section ${id} end -->`;

const oneLine = (s: string): string => s.replace(/\s+/g, ' ').trim();

/** The body of the managed `seed` section: project-wide rules first, then one group per interest. */
export function renderTasteSeedSection(
  rules: readonly TasteSeedLine[],
  interestNames: Readonly<Record<string, string>> = {},
): string {
  const lines: string[] = ['## Explicit rules', ''];
  const general = rules.filter((r) => !r.interestId || !interestNames[r.interestId]);
  if (rules.length === 0) lines.push('_No explicit rules yet._', '');
  for (const r of general) lines.push(`- Rule: ${oneLine(r.text)}`);
  if (general.length) lines.push('');
  const groups = new Map<string, string[]>();
  for (const r of rules) {
    if (!r.interestId || !interestNames[r.interestId]) continue;
    groups.set(r.interestId, [...(groups.get(r.interestId) ?? []), r.text]);
  }
  for (const [id, texts] of groups) {
    lines.push(`### ${oneLine(interestNames[id] as string)} (interest)`, '');
    for (const t of texts) lines.push(`- Rule: ${oneLine(t)}`);
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const blockRe = (id: string): RegExp =>
  new RegExp(
    `<!-- aom:section ${escapeRe(id)} v=(\\d+) begin[^\\n]*?-->[\\s\\S]*?<!-- aom:section ${escapeRe(id)} end -->[ \\t]*(?:\\r?\\n)?`,
  );

/**
 * Puts a site-managed block into a markdown file: a missing file becomes `header + block`; a block that is already
 * there with `v >= version` is left alone (a stale or duplicate write); an older block is replaced between its markers;
 * without a block it goes right after the header paragraph (before the first `- ` line), else at the end.
 */
export function applyManagedSection(
  current: string | null,
  header: string,
  id: string,
  version: number,
  content: string,
): { text: string; changed: boolean } {
  const block = `${sectionBegin(id, version)}\n${content.trim()}\n${sectionEnd(id)}\n`;
  if (current === null || current.trim() === '') return { text: `${header}${block}`, changed: true };
  const m = blockRe(id).exec(current);
  if (m) {
    if (Number(m[1]) >= version) return { text: current, changed: false };
    return {
      text: `${current.slice(0, m.index)}${block}${current.slice(m.index + m[0].length)}`,
      changed: true,
    };
  }
  const firstRule = /^- /m.exec(current);
  if (firstRule) {
    const before = current.slice(0, firstRule.index).replace(/\s*$/, '\n\n');
    return { text: `${before}${block}\n${current.slice(firstRule.index)}`, changed: true };
  }
  return { text: `${current.replace(/\s*$/, '\n\n')}${block}`, changed: true };
}

/** `taste.md` without the managed block, so the rules never appear twice in a curator's brief. */
export function stripManagedSection(text: string, id: string = TASTE_SEED_SECTION_ID): string {
  return text
    .replace(blockRe(id), '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
