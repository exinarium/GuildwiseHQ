/**
 * `compileSetup`: the pure, deterministic compiler from `setup.json` to the files of `delivery/` (design section 4.2).
 *
 * - Same input and generator, same bytes. No clock, no randomness, no environment.
 * - Every user value passed the strict character sets of `setup.ts` and is single-quoted again by `shq()`; remote work is
 *   `ssh host "bash -s -- <printf %q args>"` with the script on stdin from a quoted heredoc, so no value is ever
 *   interpolated into a remote command line unquoted.
 * - Every script follows the script contract (docs/design/ceo-front-door.md 9.2): `set -euo pipefail`, a lock, safe to rerun
 *   ("already deployed" ends it), `AOM_DEPLOY_DRY_RUN=1` runs only the read-only checks and prints "would ...", and a final
 *   `AOM-DEPLOY {json}` line.
 * - Nothing here ever runs `down`, `rm` on a container, `-v`, `--remove-orphans` or `prune`: only the named service is
 *   restarted (`--no-deps`).
 */

export interface CompiledFile {
  path: string;
  mode: '755' | '644';
  content: string;
}

export interface CompiledSetup {
  files: CompiledFile[];
  /** Files of environments in `custom` mode that are kept from the current `delivery/` (the runner copies them over). */
  keep: string[];
  /** The `recipe.yaml` environments as plain data (also in `files`). */
  recipe: { version: 1; environments: Array<Record<string, unknown>> };
  /** Content hash of the generated files: what the preview shows and `publish` must repeat. */
  hash: string;
  setup: DeliverySetup;
}

export type CompileResult = ({ ok: true } & CompiledSetup) | { ok: false; issues: string[] };

/** Single quotes around a value; `'` becomes `'\''`. The only way a value enters a script. */
export function shq(s: string): string {
  if (s.includes('\0')) throw new Error('a value contains a NUL character');
  return `'${s.replace(/'/g, `'\\''`)}'`;
}

/** A local path as a shell word: `~/x` becomes `"$HOME"'/x'`. */
export function pathWord(p: string): string {
  if (p === '~') return '"$HOME"';
  if (p.startsWith('~/')) return `"$HOME"${shq(p.slice(1))}`;
  return shq(p);
}

/** A health URL as a shell word; `${appUrl}` becomes the target's address from `AOM_DEPLOY_APP_URL`. */
export function urlWord(url: string): string {
  return url
    .split('${appUrl}')
    .map((part) => (part ? shq(part) : ''))
    .join('"${AOM_DEPLOY_APP_URL:-}"');
}

/** Bash written with `@{` instead of `${` (so TypeScript does not interpolate it); backslashes stay as written. */
export const sh = (strings: TemplateStringsArray, ...vals: string[]): string =>
  String.raw(strings, ...vals).replaceAll('@{', '${');

export const lines = (...parts: Array<string | Array<string | null> | null | false | undefined>): string =>
  `${parts
    .flatMap((p) => (p === null || p === undefined || p === false ? [] : Array.isArray(p) ? p : [p]))
    .join('\n')}\n`;

const shellPath = (name: string) => `scripts/${name}.sh`;

