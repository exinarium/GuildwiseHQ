/** The health address must be a web address before anything changes (an empty `AOM_DEPLOY_APP_URL` would make a bad address). */
export const healthUrlCheck = (env: SetupEnv): string[] =>
  env.health.kind === 'http'
    ? [
        sh`[[ "$HEALTH_URL" =~ ^https?:// ]] || die "the health address ($HEALTH_URL) is not a web address: set the address of the app on its deploy target"`,
      ]
    : [];

export function commitChecks(): string[] {
  return [
    sh`[[ "$COMMIT" =~ ^[0-9a-f]{7,64}$ ]] || die "AOM_DEPLOY_COMMIT must be a commit id"`,
    sh`SHORT="@{COMMIT:0:12}"`,
    'TAG="$IMAGE:$SHORT"',
  ];
}

export const lockBlock = (name: string): string[] => [
  'if command -v flock >/dev/null 2>&1; then',
  sh`  LOCK_DIR="@{XDG_RUNTIME_DIR:-$HOME/.cache}"`,
  '  mkdir -p -- "$LOCK_DIR" 2>/dev/null || LOCK_DIR=/tmp',
  sh`  LOCK_PROJECT="@{AOM_DEPLOY_PROJECT_ID:-x}"`,
  sh`  exec 9>"$LOCK_DIR/aom-deploy-@{LOCK_PROJECT//[^A-Za-z0-9-]/}-${name}.lock"`,
  '  flock -n 9 || die "another deploy of $ENV_NAME is running"',
  'fi',
];

export function stepNumberComment(i: number, text: string): string[] {
  return ['', `# step ${i + 1}: ${text.replace(/[\r\n]+/g, ' ')}`];
}

const customArgv = (s: Extract<DeployStep, { kind: 'custom_command' }>) => s.argv.map(shq).join(' ');

// ------------------------------------------------------------------------------------------------ this computer

function localScript(setup: DeliverySetup, env: SetupEnv): string {
  const a = env.app;
  const out: Array<string | null> = [...header(setup, env)];
  out.push(
    `ENV_NAME=${shq(env.name)}`,
    `SERVICE=${shq(a.service)}`,
    `IMAGE=${shq(a.imageName)}`,
    `KEEP_IMAGES=${a.imageKeep}`,
    `COMPOSE_FILE=${pathWord(a.composeFile)}`,
    a.composeProject ? `COMPOSE_PROJECT=${shq(a.composeProject)}` : null,
    env.health.kind === 'http' ? `HEALTH_URL=${urlWord(env.health.url)}` : null,
    `HEALTH_TIMEOUT=${env.healthTimeoutSec}`,
    '',
  );
  out.push(...commonFunctions());
  out.push(...healthFunctions(env));
  out.push(...doneFunction());
  out.push(
    ...commitChecks(),
    ...healthUrlCheck(env),
    '[ -d "$CHECKOUT" ] || die "AOM_DEPLOY_CHECKOUT is not a folder"',
    sh`case "$CHECKOUT" in /*) ;; *) die "AOM_DEPLOY_CHECKOUT must be a full path" ;; esac`,
    sh`case "$CHECKOUT" in *[!A-Za-z0-9._/+@=-]*) die "the checkout path has unusual characters" ;; esac`,
    '',
    ...lockBlock(`${a.composeProject ?? a.service}-${env.name}`),
    '',
    'type -P docker >/dev/null 2>&1 || die "docker is not installed on this computer"',
    ...curlCheck(env),
    'docker compose version >/dev/null 2>&1 || die "docker compose (version 2) is not available"',
    sh`say "tools: docker engine $(docker version --format '{{.Server.Version}}' 2>/dev/null || echo unknown), docker compose $(docker compose version --short 2>/dev/null || echo unknown)"`,
    '[ -f "$COMPOSE_FILE" ] || die "the compose file $COMPOSE_FILE does not exist"',
    a.composeProject
      ? sh`dc() { docker compose -p "$COMPOSE_PROJECT" -f "$COMPOSE_FILE" "$@"; }`
      : sh`dc() { docker compose -f "$COMPOSE_FILE" "$@"; }`,
    'dc config --services | grep -x -- "$SERVICE" >/dev/null || die "the compose file has no service called $SERVICE"',
    '',
    'WORK="$(mktemp -d "${TMPDIR:-/tmp}/aom-deploy.XXXXXX")"',
    `trap 'rm -rf -- "$WORK"' EXIT`,
    '',
    'running_image() {',
    '  local id',
    sh`  id="$(dc ps -q "$SERVICE" 2>/dev/null | head -n 1)" || id=`,
    '  [ -n "$id" ] || return 0',
    sh`  docker inspect --format '{{.Config.Image}}' "$id" 2>/dev/null || true`,
    '}',
    '# the running app must have been started from the compose file named in the setup (not several files or another project folder)',
    'fail() { die "$1"; }',
    'check_origin() {',
    '  local id lab l_cfg l_rest l_wd l_proj l_env l_first l_more file dir proj',
    '  file="$COMPOSE_FILE"; dir="$(dirname -- "$COMPOSE_FILE")"; proj="${COMPOSE_PROJECT:-}"',
    sh`  id="$(dc ps -q "$SERVICE" 2>/dev/null | head -n 1)" || id=`,
    ...originCheck('  ', 'temporary_override'),
    '}',
    'check_origin',
    'PREVIOUS="$(running_image)"',
    sh`case "$PREVIOUS" in *[!A-Za-z0-9._/:@-]*) PREVIOUS="" ;; esac`,
    'say "running now: ${PREVIOUS:-nothing}"',
    '',
    ...localGuard(env),
    '',
    'if [ "$PREVIOUS" = "$TAG" ] && healthy; then',
    '  say "already deployed: $TAG is running and healthy"',
    '  done_line',
    '  exit 0',
    'fi',
    '[ "$DRY_RUN" = 1 ] && say "dry run: only checking, nothing will be changed"',
    'BACKUP_FILE=""',
  );
  env.steps.forEach((s, i) => {
    out.push(...localStep(s, i, env));
  });
  out.push(...localTail(env));
  return lines(out);
}

/** Everything after the switch is undone when the script ends early (any failure, TERM, INT), unless it finished. */
function localGuard(env: SetupEnv): string[] {
  return [
    '# if anything ends this script after the app was switched, put the previous version back',
    'SWITCHED=0',
    'FINISHED=0',
    'on_exit() {',
    '  local rc=$?',
    '  trap - EXIT',
    '  if [ "$SWITCHED" = 1 ] && [ "$FINISHED" != 1 ]; then',
    ...(env.rollback
      ? [
          '    if [ -n "$PREVIOUS" ] && [ "$PREVIOUS" != "$TAG" ]; then',
          '      say "putting the previous version back: $PREVIOUS"',
          `      printf 'services:\\n  %s:\\n    image: "%s"\\n' "$SERVICE" "$PREVIOUS" > "$WORK/rollback.yml"`,
          '      if dc -f "$WORK/rollback.yml" up -d --no-build --no-deps "$SERVICE"; then',
          '        if wait_healthy 60; then say "rolled back to $PREVIOUS"; else say "still not healthy after going back to $PREVIOUS"; fi',
          '      else',
          '        say "ROLLBACK FAILED: $SERVICE may still be running $TAG. Put $PREVIOUS back by hand."',
          '      fi',
          '      [ -z "$BACKUP_FILE" ] || say "the database was NOT rolled back; the backup made before this update is $BACKUP_FILE"',
          '    else',
          '      say "there is no previous version to go back to; $SERVICE may be running $TAG"',
          '    fi',
        ]
      : ['    say "automatic rollback is switched off; $SERVICE may be running $TAG"']),
    '  fi',
    '  rm -rf -- "$WORK"',
    '  if [ "$rc" -eq 0 ] && [ "$SWITCHED" = 1 ] && [ "$FINISHED" != 1 ]; then rc=1; fi',
    '  exit "$rc"',
    '}',
    'trap on_exit EXIT',
    "trap 'exit 143' TERM",
    "trap 'exit 130' INT",
  ];
}

function localStep(s: DeployStep, i: number, env: SetupEnv): string[] {
  const a = env.app;
  switch (s.kind) {
    case 'db_backup':
      return [
        ...stepNumberComment(i, 'back up the database'),
        `BACKUP_DIR=${pathWord(s.dir)}`,
        `DB_SERVICE=${shq(s.service)}`,
        `DB_USER=${shq(s.dbUser ?? '')}`,
        `DB_NAME=${shq(s.dbName ?? '')}`,
        `KEEP_BACKUPS=${s.keep}`,
        'if [ "$DRY_RUN" = 1 ]; then',
        '  would "back up the database ($DB_SERVICE) to $BACKUP_DIR, keeping the newest $KEEP_BACKUPS"',
        '  [ -n "$(dc ps -q "$DB_SERVICE")" ] || die "the database service $DB_SERVICE is not running"',
        'else',
        '  (umask 077; mkdir -p -- "$BACKUP_DIR")',
        '  BACKUP_FILE="$BACKUP_DIR/$ENV_NAME-before-$SHORT-$(date +%Y%m%d-%H%M%S).sql.gz"',
        `  if ! (umask 077; dc exec -T "$DB_SERVICE" sh -c ${shq('pg_dump -U "${1:-$POSTGRES_USER}" -d "${2:-$POSTGRES_DB}"')} sh "$DB_USER" "$DB_NAME" </dev/null | gzip > "$BACKUP_FILE.part"); then`,
        '    rm -f -- "$BACKUP_FILE.part"',
        '    die "the database backup failed; nothing was changed"',
        '  fi',
        '  if [ "$(gzip -dc "$BACKUP_FILE.part" | wc -c)" -lt 512 ]; then',
        '    rm -f -- "$BACKUP_FILE.part"',
        '    die "the database backup is too small to be real; nothing was changed"',
        '  fi',
        '  mv -- "$BACKUP_FILE.part" "$BACKUP_FILE"',
        '  [ -s "$BACKUP_FILE" ] || die "the database backup file is missing after it was saved; nothing was changed"',
        '  say "backup saved: $BACKUP_FILE"',
        '  if [ "$KEEP_BACKUPS" -gt 0 ]; then',
        sh`    ls -1t -- "$BACKUP_DIR"/"$ENV_NAME"-before-*.sql.gz 2>/dev/null | tail -n +$((KEEP_BACKUPS + 1)) | while IFS= read -r old; do rm -f -- "$old"; done || true`,
        '  fi',
        'fi',
      ];
    case 'compose_up_local':
      return [
        ...stepNumberComment(i, `rebuild and restart only ${a.service}`),
        'if [ "$DRY_RUN" = 1 ]; then',
        '  would "build $TAG from the approved version and restart only $SERVICE (nothing else is stopped)"',
        '  dc config -q || die "the compose file does not validate"',
        'else',
        '  OVERRIDE="$WORK/override.yml"',
        `  printf 'services:\\n  %s:\\n    build: "%s"\\n    image: "%s"\\n' "$SERVICE" "$CHECKOUT" "$TAG" > "$OVERRIDE"`,
        '  SWITCHED=1',
        '  dc -f "$OVERRIDE" up -d --build --no-deps "$SERVICE"',
        'fi',
      ];
    case 'compose_run':
      return [
        ...stepNumberComment(i, s.label),
        `RUN_SERVICE=${shq(s.service ?? a.service)}`,
        'if [ "$DRY_RUN" = 1 ]; then',
        `  would ${shq(`${s.label}: run ${s.argv.join(' ')} in the new version of the app (the database is backed up first)`)}`,
        '  dc config -q || die "the compose file does not validate"',
        'else',
        '  OVERRIDE="$WORK/override.yml"',
        `  printf 'services:\\n  %s:\\n    build: "%s"\\n    image: "%s"\\n' "$RUN_SERVICE" "$CHECKOUT" "$TAG" > "$OVERRIDE"`,
        '  dc -f "$OVERRIDE" build "$RUN_SERVICE"',
        `  if ! dc -f "$OVERRIDE" run --rm -T "$RUN_SERVICE" ${s.argv.map(shq).join(' ')} </dev/null; then`,
        '    die "the database updates failed; the app was not restarted"',
        '  fi',
        'fi',
      ];
    case 'custom_command':
      return [
        ...stepNumberComment(i, s.label),
        'if [ "$DRY_RUN" = 1 ]; then',
        `  would ${shq(s.label)}`,
        'else',
        `  ${customArgv(s)}`,
        'fi',
      ];
    default:
      return [
        `# step ${i + 1}: ${s.kind} is not available on this computer`,
        'die "this step is not available here"',
      ];
  }
}

function localTail(env: SetupEnv): string[] {
  const out: string[] = ['', '# the end: check, go back if needed, tidy up'];
  out.push(
    'if [ "$DRY_RUN" = 1 ]; then',
    env.health.kind === 'http'
      ? '  would "check $HEALTH_URL answers, and put the previous version back if it does not"'
      : '  would "let Guildwise check the site"',
    '  say "dry run finished: nothing was changed"',
    '  exit 0',
    'fi',
  );
  if (env.health.kind === 'http')
    out.push(
      'if ! wait_healthy "$HEALTH_TIMEOUT"; then',
      '  say "the site did not become healthy within ${HEALTH_TIMEOUT}s"',
      '  die "the update failed (the previous version is put back when it can be)"',
      'fi',
    );
  out.push('FINISHED=1');
  out.push(
    '',
    '# remove old copies of the image (never the one that runs or the one before it)',
    'n=0',
    sh`docker image ls --format '{{.Repository}}:{{.Tag}}' "$IMAGE" 2>/dev/null | while IFS= read -r ref; do`,
    '  tag="${ref##*:}"',
    '  [[ "$tag" =~ ^[0-9a-f]{12}$ ]] || continue',
    '  n=$((n + 1))',
    '  [ "$n" -gt "$KEEP_IMAGES" ] || continue',
    '  [ "$ref" != "$TAG" ] && [ "$ref" != "$PREVIOUS" ] || continue',
    '  docker image rm "$ref" >/dev/null 2>&1 || true',
    'done || true',
    '',
    'done_line',
  );
  return out;
}

// ------------------------------------------------------------------------------------------------ a server over ssh

export function sshHelpers(): string[] {
  return [
    sh`HOST="@{AOM_DEPLOY_HOST:-}"`,
    sh`case "$HOST" in ''|-*|*[!A-Za-z0-9._-]*) die "AOM_DEPLOY_HOST must be the server name (letters, digits, . _ -)" ;; esac`,
    sh`read -r -a SSH_CMD <<< "@{AOM_DEPLOY_SSH:-ssh}"`,
    'SSH_OPTS=(-o BatchMode=yes -o ConnectTimeout=15 -o StrictHostKeyChecking=yes)',
    '# one command string on the server',
    sh`rsh() { "@{SSH_CMD[@]}" "@{SSH_OPTS[@]}" -- "$HOST" "$1" 9>&-; }`,
    '# arguments for a remote command line, quoted',
    `rquote() { local a out=''; for a in "$@"; do out+=" $(printf '%q' "$a")"; done; printf '%s' "$out"; }`,
    '# "docker compose" (version 2) or "docker-compose" (version 1): whichever the server has',
    `REMOTE_PRE='dc() { if docker compose version >/dev/null 2>&1; then docker compose "$@"; elif docker-compose version >/dev/null 2>&1; then docker-compose "$@"; else echo "AOM: the server has neither docker compose nor docker-compose" >&2; return 127; fi; }'`,
    '# a script, run on the server with these arguments as $1 $2 ... The script travels as an ARGUMENT (base64, so there is nothing',
    '# to quote), never on stdin: a docker command that reads stdin cannot swallow the rest of it. The remote stdin is empty.',
    'remote() {',
    '  local b64',
    `  b64="$({ printf '%s\\n' "$REMOTE_PRE"; cat; } | base64 | tr -d '\\n')"`,
    '  rsh "bash -c \\"\\$(printf %s $b64 | base64 -d)\\" aom-remote$(rquote "$@")" </dev/null',
    '}',
    '',
  ];
}

/**
 * awk program: the value of `VAR` in a dotenv file. Handles `export VAR=...`, double and single quotes, a trailing `# comment`
 * (unquoted values) and CRLF line ends; the last assignment wins, as in dotenv loaders.
 */
export const ENV_VALUE_AWK = String.raw`BEGIN { v = ENVIRON["VAR"] } { sub(/\r$/, ""); l = $0; sub(/^[ \t]*(export[ \t]+)?/, "", l); if (index(l, v "=") != 1) next; val = substr(l, length(v) + 2); sub(/^[ \t]+/, "", val); if (val ~ /^"/) { sub(/^"/, "", val); sub(/".*$/, "", val) } else if (val ~ /^\047/) { sub(/^\047/, "", val); sub(/\047.*$/, "", val) } else { sub(/[ \t]+#.*$/, "", val); sub(/[ \t]+$/, "", val) } last = val } END { print last }`;

/**
 * The running app container says how it was started (labels written by `docker compose`). Guildwise restarts it with
 * `-f <the compose file> [-p project]` in that folder; if the stack was really started another way (several files, another
 * project folder, an --env-file) a restart would recreate it differently, so it stops first with a plain message. Needs the shell
 * variables `id` (container), `file`, `dir`, optional `proj`, and a `fail "message"` function.
 */
/**
 * The temporary compose files a local deploy or rollback adds to `docker compose` (`-f <compose> -f $TMPDIR/aom-deploy.XXXXXX/override.yml`).
 * They end up in the stack's `config_files` label, so the deploy script and the runner's probe must both accept exactly these and
 * nothing else as "not a second compose file". This is the one definition: the shell `case` patterns and the TypeScript check are
 * both built from it.
 */
export const TEMP_OVERRIDE_DIR_PREFIX = 'aom-deploy.';
export const TEMP_OVERRIDE_FILE_NAMES = ['override.yml', 'rollback.yml'] as const;
/** `mktemp -d .../aom-deploy.XXXXXX` leaves six characters. */
const TEMP_OVERRIDE_SUFFIX_LENGTH = 6;

/** The shell `case` patterns that match the temporary files, joined with `|`. */
export const TEMP_OVERRIDE_CASE_PATTERNS = TEMP_OVERRIDE_FILE_NAMES.map(
  (n) => `*/${TEMP_OVERRIDE_DIR_PREFIX}${'?'.repeat(TEMP_OVERRIDE_SUFFIX_LENGTH)}/${n}`,
).join('|');

/** True when the path is one of the temporary files of a Guildwise deploy or rollback (the same paths the deploy script accepts). */
export function isGuildwiseTemporaryOverride(path: string): boolean {
  const m = /^(.*)\/([^/]*)\/([^/]*)$/.exec(path.trim());
  if (!m) return false;
  const dir = m[2] ?? '';
  return (
    dir.length === TEMP_OVERRIDE_DIR_PREFIX.length + TEMP_OVERRIDE_SUFFIX_LENGTH &&
    dir.startsWith(TEMP_OVERRIDE_DIR_PREFIX) &&
    (TEMP_OVERRIDE_FILE_NAMES as readonly string[]).includes(m[3] ?? '')
  );
}

function originCheck(indent: string, extra: 'none' | 'guildwise_override' | 'temporary_override'): string[] {
  const fmt = [
    'com.docker.compose.project.config_files',
    'com.docker.compose.project.working_dir',
    'com.docker.compose.project',
    'com.docker.compose.project.environment_file',
  ]
    .map((l) => `{{index .Config.Labels "${l}"}}`)
    .join('|');
  return [
    `if [ -n "$id" ]; then`,
    `  lab=$(docker inspect --format '${fmt}' "$id" 2>/dev/null) || lab=`,
    '  if [ -n "$lab" ]; then',
    '    l_cfg=${lab%%|*}; l_rest=${lab#*|}; l_wd=${l_rest%%|*}; l_rest=${l_rest#*|}; l_proj=${l_rest%%|*}; l_env=${l_rest#*|}',
    '    rl() { readlink -f -- "$1" 2>/dev/null || printf \'%s\\n\' "$1"; }',
    '    # the files: the one in the setup, and at most the override file that Guildwise itself writes next to it',
    '    l_first=${l_cfg%%,*}; l_more=${l_cfg#"$l_first"}; l_more=${l_more#,}',
    '    [ -z "$l_cfg" ] || [ "$(rl "$l_first")" = "$(rl "$file")" ] || fail "the app was started from $l_first, not from $file. Guildwise only updates an app that runs from the one compose file named in the setup: point the setup at $l_first, or restart the app from $file yourself first. Nothing was changed"',
    ...(extra === 'none'
      ? [
          '    [ -z "$l_more" ] || fail "the app was started from several compose files ($l_cfg). Guildwise does not support that yet, so it will not restart it: nothing was changed"',
        ]
      : [
          `    case "$l_more" in`,
          '      *,*) fail "the app was started from several compose files ($l_cfg). Guildwise does not support that yet, so it will not restart it: nothing was changed" ;;',
          '      "") ;;',
          extra === 'guildwise_override'
            ? `      *) [ "$(rl "$l_more")" = "$(rl "$dir/${OVERRIDE_NAME}")" ] || fail "the app was started from several compose files ($l_cfg). Guildwise does not support that yet, so it will not restart it: nothing was changed" ;;`
            : `      ${TEMP_OVERRIDE_CASE_PATTERNS}) ;; *) fail "the app was started from several compose files ($l_cfg). Guildwise does not support that yet, so it will not restart it: nothing was changed" ;;`,
          '    esac',
        ]),
    '    [ -z "$l_wd" ] || [ "$(rl "$l_wd")" = "$(rl "$dir")" ] || fail "the app was started with another project folder ($l_wd) than the folder of its compose file ($dir). Guildwise does not support that yet: nothing was changed"',
    '    [ -z "$l_env" ] || fail "the app was started with its own settings file option (--env-file $l_env). Guildwise does not support that yet: nothing was changed"',
    '    [ -z "${proj:-}" ] || [ -z "$l_proj" ] || [ "$l_proj" = "$proj" ] || fail "the app runs in the compose project $l_proj, not $proj as the setup says: nothing was changed"',
    '  fi',
    'fi',
  ].map((l) => (l ? indent + l : l));
}

function remoteState(env: SetupEnv): string[] {
  const p = !!env.app.composeProject;
  return [
    `STATE="$(remote "$APP_DIR" "$COMPOSE_FILE" "$IMAGE_VAR" "$SERVICE"${p ? ' "$COMPOSE_PROJECT"' : ''} <<'AOM_REMOTE'`,
    'set -eu',
    p ? 'dir=$1; file=$2; var=$3; svc=$4; proj=$5' : 'dir=$1; file=$2; var=$3; svc=$4',
    '[ -d "$dir" ] || { echo "AOM: there is no folder $dir on the server" >&2; exit 21; }',
    '[ -f "$file" ] || { echo "AOM: there is no compose file $file on the server" >&2; exit 22; }',
    'docker info >/dev/null 2>&1 || { echo "AOM: docker is not usable by this user on the server" >&2; exit 23; }',
    'cur=',
    'if [ -f "$dir/.env" ]; then cur=$(VAR="$var" awk \'' + ENV_VALUE_AWK + '\' "$dir/.env"); fi',
    'run=',
    p
      ? 'id=$(cd "$dir" && dc -p "$proj" -f "$file" ps -q "$svc" 2>/dev/null | head -n 1) || id='
      : 'id=$(cd "$dir" && dc -f "$file" ps -q "$svc" 2>/dev/null | head -n 1) || id=',
    'fail() { echo "AOM: $1" >&2; exit 24; }',
    ...originCheck('', usesOverride(env) ? 'guildwise_override' : 'none'),
    `if [ -n "$id" ]; then run=$(docker inspect --format '{{.Config.Image}}' "$id" 2>/dev/null) || run=; fi`,
    ...(usesOverride(env) ? ['ovr=0; [ -f "$dir/' + OVERRIDE_NAME + '" ] && ovr=1'] : ['ovr=0']),
    `engine=$(docker version --format '{{.Server.Version}}' 2>/dev/null) || engine=`,
    'comp=',
    'if docker compose version >/dev/null 2>&1; then comp="v2 $(docker compose version --short 2>/dev/null)"',
    'elif docker-compose version >/dev/null 2>&1; then comp="v1 $(docker-compose version --short 2>/dev/null)"; fi',
    `printf 'image=%s\\nrunning=%s\\nengine=%s\\ncompose=%s\\noverride=%s\\n' "$cur" "$run" "$engine" "$comp" "$ovr"`,
    'AOM_REMOTE',
    ')" || die "could not look at the server"',
    `CURRENT_IMAGE="$(printf '%s\\n' "$STATE" | sed -n 's/^image=//p' | head -n 1)"`,
    `RUNNING_IMAGE="$(printf '%s\\n' "$STATE" | sed -n 's/^running=//p' | head -n 1)"`,
    `OVERRIDE_BEFORE="$(printf '%s\\n' "$STATE" | sed -n 's/^override=//p' | head -n 1 | tr -cd '01')"`,
    sh`case "$CURRENT_IMAGE" in *[!A-Za-z0-9._/:@-]*) CURRENT_IMAGE="" ;; esac`,
    sh`case "$RUNNING_IMAGE" in *[!A-Za-z0-9._/:@-]*) RUNNING_IMAGE="" ;; esac`,
    'say "server runs: ${RUNNING_IMAGE:-nothing}; settings point at: ${CURRENT_IMAGE:-nothing}"',
    `ENGINE_VERSION="$(printf '%s\\n' "$STATE" | sed -n 's/^engine=//p' | head -n 1 | tr -cd '0-9A-Za-z._+-')"`,
    `COMPOSE_VERSION="$(printf '%s\\n' "$STATE" | sed -n 's/^compose=//p' | head -n 1 | tr -cd '0-9A-Za-z._+ -')"`,
    'say "server tools: docker engine ${ENGINE_VERSION:-unknown}, docker compose ${COMPOSE_VERSION:-unknown}"',
    sh`case "$COMPOSE_VERSION" in`,
    '  v1*)',
    '    if [[ "${ENGINE_VERSION%%.*}" =~ ^[0-9]+$ ]] && [ "${ENGINE_VERSION%%.*}" -ge 25 ]; then',
    '      say "WARNING: this server uses docker-compose version 1 with Docker engine ${ENGINE_VERSION}. Restarting a service can then fail with a \'ContainerConfig\' KeyError."',
    '      say "WARNING: Guildwise will not remove or recreate other parts to work around it. Install Docker Compose version 2 (the \'docker compose\' command); stopping the app by hand first is a downtime you decide."',
    '    fi ;;',
    'esac',
  ];
}

/** The override file next to the compose file that names the new image when there is no `.env` variable. */
export const OVERRIDE_NAME = 'docker-compose.guildwise.yml';
const usesOverride = (env: SetupEnv): boolean => !env.app.imageVar;
/** The shell function that switches the server to image "$1" (and back, on rollback). */
const switchFn = (env: SetupEnv): string => (usesOverride(env) ? 'write_override' : 'set_image_var');
/** The function that puts the previous image back on a rollback. */
const rollbackFn = (env: SetupEnv): string => (usesOverride(env) ? 'rollback_override' : 'set_image_var');

function sshFunctions(env: SetupEnv): string[] {
  const proj = env.app.composeProject ? '"$COMPOSE_PROJECT"' : '""';
  const ov = usesOverride(env);
  return [
    ...(ov
      ? [
          '# name the new image in an override file next to the compose file (the compose file and .env are never edited)',
          'write_override() {',
          '  remote "$APP_DIR" "$SERVICE" "$1" "$SHORT" <<\'AOM_REMOTE\'',
          'set -eu',
          'dir=$1; svc=$2; tag=$3; short=$4',
          `ov="$dir/${OVERRIDE_NAME}"`,
          'tmp="$ov.aom-tmp.$$"',
          `trap 'rm -f -- "$tmp"' EXIT`,
          'if [ -f "$ov" ] && [ ! -e "$ov.bak-before-$short" ]; then cp -p -- "$ov" "$ov.bak-before-$short"; fi',
          `printf '# Written by Guildwise. It names the version that runs; your own compose file is not changed.\\nservices:\\n  %s:\\n    image: "%s"\\n' "$svc" "$tag" > "$tmp"`,
          'mv -- "$tmp" "$ov"',
          'echo "set the image of $svc to $tag in $ov" >&2',
          'AOM_REMOTE',
          '}',
          '# going back when there was no override file before this update: remove the one this update made (the compose file names its own image)',
          'remove_override() {',
          '  remote "$APP_DIR" <<\'AOM_REMOTE\'',
          'set -eu',
          `ov="$1/${OVERRIDE_NAME}"`,
          'rm -f -- "$ov"',
          'echo "removed $ov: the compose file names the image again" >&2',
          'AOM_REMOTE',
          '}',
          'rollback_override() { if [ "${OVERRIDE_BEFORE:-0}" = 1 ]; then write_override "$1"; else remove_override; fi; }',
        ]
      : [
          "# switch exactly one line of the server's .env (a temporary copy is moved over it)",
          'set_image_var() {',
          '  remote "$APP_DIR" "$IMAGE_VAR" "$1" <<\'AOM_REMOTE\'',
          'set -eu',
          'dir=$1; var=$2; val=$3',
          'envf="$dir/.env"',
          '[ -f "$envf" ] || { echo "AOM: there is no .env in $dir" >&2; exit 51; }',
          'tmp="$envf.aom-tmp.$$"',
          `trap 'rm -f -- "$tmp"' EXIT`,
          'cp -p -- "$envf" "$tmp"',
          `VAR="$var" VAL="$val" awk 'BEGIN { v = ENVIRON["VAR"]; n = ENVIRON["VAL"]; done = 0 }`,
          '  { cr = ($0 ~ /\r$/ ? "\r" : ""); l = $0; sub(/\r$/, "", l); sub(/^[ \t]*(export[ \t]+)?/, "", l) }',
          '  index(l, v "=") == 1 { if (!done) print v "=" n cr; done = 1; next }',
          '  { print }',
          `  END { if (!done) print v "=" n cr }' "$envf" > "$tmp"`,
          'mv -- "$tmp" "$envf"',
          'echo "set $var in $envf" >&2',
          'AOM_REMOTE',
          '}',
        ]),
    '# restart only the app service (never down, never other services)',
    'compose_up_remote() {',
    `  remote "$APP_DIR" "$COMPOSE_FILE" "$SERVICE" "$1" ${proj} <<'AOM_REMOTE'`,
    'set -eu',
    'dir=$1; file=$2; svc=$3; dry=$4; proj=$5',
    'cd "$dir"',
    'if [ -n "$proj" ]; then set -- -p "$proj" -f "$file"; else set -- -f "$file"; fi',
    ...(ov ? [`[ ! -f "$dir/${OVERRIDE_NAME}" ] || set -- "$@" -f "$dir/${OVERRIDE_NAME}"`] : []),
    'if [ "$dry" = 1 ]; then dc "$@" config -q; echo "would restart only $svc" >&2; exit 0; fi',
    ov ? 'dc "$@" up -d --no-deps --no-build "$svc"' : 'dc "$@" up -d --no-deps "$svc"',
    'AOM_REMOTE',
    '}',
    ...(env.steps.some((x) => x.kind === 'compose_run')
      ? [
          '# run a command in the new image on the server (the .env keeps the old image until the switch)',
          'compose_run_remote() {',
          '  local dry="$1" svc="$2"; shift 2',
          `  remote "$APP_DIR" "$COMPOSE_FILE" "$svc" "$IMAGE_VAR" "$TAG" "$dry" ${proj} "$@" <<'AOM_REMOTE'`,
          'set -eu',
          'dir=$1; file=$2; svc=$3; var=$4; tag=$5; dry=$6; proj=$7; shift 7',
          'cd "$dir"',
          'pa=(-f "$file"); [ -z "$proj" ] || pa=(-p "$proj" -f "$file")',
          'if [ "$dry" = 1 ]; then dc "${pa[@]}" config -q; echo "would run the database updates in $svc" >&2; exit 0; fi',
          ...(ov
            ? [
                `[ ! -f "$dir/${OVERRIDE_NAME}" ] || pa+=(-f "$dir/${OVERRIDE_NAME}")`,
                'tmpd=$(mktemp -d); trap \'rm -rf -- "$tmpd"\' EXIT',
                `printf 'services:\\n  %s:\\n    image: "%s"\\n' "$svc" "$tag" > "$tmpd/run.yml"`,
                'pa+=(-f "$tmpd/run.yml")',
              ]
            : ['export "$var=$tag"']),
          'dc "${pa[@]}" run --rm -T "$svc" "$@" </dev/null',
          'AOM_REMOTE',
          '}',
        ]
      : []),
    '',
  ];
}

function sshScript(setup: DeliverySetup, env: SetupEnv): string {
  const a = env.app;
  const dir = a.composeFile.slice(0, a.composeFile.lastIndexOf('/')) || '/';
  const method = updateMethodOf(env);
  const out: Array<string | null> = [...header(setup, env)];
  out.push(
    `ENV_NAME=${shq(env.name)}`,
    `SERVICE=${shq(a.service)}`,
    `IMAGE=${shq(a.imageName)}`,
    `IMAGE_VAR=${shq(a.imageVar ?? '')}`,
    ...(a.registry ? [`REGISTRY=${shq(a.registry)}`] : []),
    ...(method === 'build_on_server'
      ? [`SRC_DIR=${shq(a.sourceDir ?? `${dir === '/' ? '' : dir}/guildwise-src`)}`]
      : []),
    `APP_DIR=${shq(dir)}`,
    `COMPOSE_FILE=${shq(a.composeFile)}`,
    a.composeProject ? `COMPOSE_PROJECT=${shq(a.composeProject)}` : null,
    env.health.kind === 'http' ? `HEALTH_URL=${urlWord(env.health.url)}` : null,
    `HEALTH_TIMEOUT=${env.healthTimeoutSec}`,
    '',
  );
  out.push(...commonFunctions());
  out.push(...healthFunctions(env));
  out.push(...doneFunction());
  out.push(
    ...commitChecks(),
    ...(a.registry ? ['TAG="$REGISTRY/$TAG"'] : []),
    ...healthUrlCheck(env),
    ...lockBlock(`${a.composeProject ?? a.service}-${env.name}`),
    '',
    ...curlCheck(env),
    ...sshHelpers(),
    ...sshFunctions(env),
    `rsh 'true' </dev/null || die "cannot sign in to $HOST without a password: check the sign-in of this computer"`,
    ...remoteState(env),
    '',
    usesOverride(env)
      ? 'if [ "$RUNNING_IMAGE" = "$TAG" ] && healthy; then'
      : 'if [ "$CURRENT_IMAGE" = "$TAG" ] && [ "$RUNNING_IMAGE" = "$TAG" ] && healthy; then',
    '  say "already deployed: $TAG is running and healthy"',
    '  done_line',
    '  exit 0',
    'fi',
    '[ "$DRY_RUN" = 1 ] && say "dry run: only checking, nothing will be changed"',
    'BACKUP_FILE=""',
    '',
    ...sshGuard(env),
  );
  env.steps.forEach((s, i) => {
    out.push(...sshStep(s, i, env));
  });
  out.push(...sshTail(env));
  return lines(out);
}

/** Everything after the image switch is undone when the script ends early (any failure, TERM, INT), unless it finished. */
function sshGuard(env: SetupEnv): string[] {
  return [
    "# the image to go back to: what runs now (it is the last one that worked), else the settings file's value",
    'PREVIOUS="${RUNNING_IMAGE:-$CURRENT_IMAGE}"',
    'SWITCHED=0',
    'FINISHED=0',
    'on_exit() {',
    '  local rc=$?',
    '  trap - EXIT',
    '  if [ "$SWITCHED" = 1 ] && [ "$FINISHED" != 1 ]; then',
    ...(env.rollback
      ? [
          '    if [ -n "$PREVIOUS" ] && [ "$PREVIOUS" != "$TAG" ]; then',
          '      say "putting the previous version back: $PREVIOUS"',
          `      if ${rollbackFn(env)} "$PREVIOUS" && compose_up_remote 0; then`,
          '        if wait_healthy 60; then say "rolled back to $PREVIOUS"; else say "still not healthy after going back to $PREVIOUS"; fi',
          '      else',
          usesOverride(env)
            ? `        say "ROLLBACK FAILED: the server may still be running $TAG. Put $PREVIOUS back by hand (the image line in ${OVERRIDE_NAME} in $APP_DIR)."`
            : '        say "ROLLBACK FAILED: the server may still be running $TAG. Settings copy: $APP_DIR/.env.bak-before-$SHORT. Put $PREVIOUS back by hand."',
          '      fi',
          '      [ -z "$BACKUP_FILE" ] || say "the database was NOT rolled back; the backup made before this update is $BACKUP_FILE"',
          '    else',
          '      say "there is no previous version to go back to; the server may be running $TAG"',
          '    fi',
        ]
      : ['    say "automatic rollback is switched off; the server may be running $TAG"']),
    '  fi',
    '  if [ "$rc" -eq 0 ] && [ "$SWITCHED" = 1 ] && [ "$FINISHED" != 1 ]; then rc=1; fi',
    '  exit "$rc"',
    '}',
    'trap on_exit EXIT',
    "trap 'exit 143' TERM",
    "trap 'exit 130' INT",
  ];
}

function sshStep(s: DeployStep, i: number, env: SetupEnv): string[] {
  const DCF = env.app.composeProject ? 'dc -p "$proj" -f "$file"' : 'dc -f "$file"';
  switch (s.kind) {
    case 'db_backup':
      return [
        ...stepNumberComment(i, 'back up the database'),
        `BACKUP_DIR=${shq(s.dir)}`,
        `DB_SERVICE=${shq(s.service)}`,
        `DB_USER=${shq(s.dbUser ?? '')}`,
        `DB_NAME=${shq(s.dbName ?? '')}`,
        `KEEP_BACKUPS=${s.keep}`,
        `BACKUP_FILE="$(remote "$APP_DIR" "$COMPOSE_FILE" "$DB_SERVICE" "$BACKUP_DIR" "$ENV_NAME" "$SHORT" "$KEEP_BACKUPS" "$DB_USER" "$DB_NAME" "$DRY_RUN"${env.app.composeProject ? ' "$COMPOSE_PROJECT"' : ''} <<'AOM_REMOTE'`,
        'set -euo pipefail',
        'dir=$1; file=$2; svc=$3; bdir=$4; env=$5; short=$6; keep=$7; dbuser=$8; dbname=$9; dry=${10}',
        ...(env.app.composeProject ? ['proj=${11}'] : []),
        'cd "$dir"',
        'if [ "$dry" = 1 ]; then',
        `  [ -n "$(${DCF} ps -q "$svc")" ] || { echo "AOM: the database service $svc is not running" >&2; exit 30; }`,
        '  echo "would: back up the database ($svc) to $bdir, keeping the newest $keep" >&2',
        '  exit 0',
        'fi',
        'umask 077',
        'mkdir -p -- "$bdir"',
        'out="$bdir/$env-before-$short-$(date +%Y%m%d-%H%M%S).sql.gz"',
        `if ! ${DCF} exec -T "$svc" sh -c ${shq('pg_dump -U "${1:-$POSTGRES_USER}" -d "${2:-$POSTGRES_DB}"')} sh "$dbuser" "$dbname" </dev/null | gzip > "$out.part"; then`,
        '  rm -f -- "$out.part"',
        '  echo "AOM: the database backup failed" >&2',
        '  exit 31',
        'fi',
        'if [ "$(gzip -dc "$out.part" | wc -c)" -lt 512 ]; then',
        '  rm -f -- "$out.part"',
        '  echo "AOM: the database backup is too small to be real" >&2',
        '  exit 32',
        'fi',
        'mv -- "$out.part" "$out"',
        '[ -s "$out" ] || { echo "AOM: the database backup file is missing after it was saved" >&2; exit 33; }',
        'if [ "$keep" -gt 0 ]; then',
        sh`  ls -1t -- "$bdir"/"$env"-before-*.sql.gz 2>/dev/null | tail -n +$((keep + 1)) | while IFS= read -r old; do rm -f -- "$old"; done || true`,
        'fi',
        `printf '%s\\n' "$out"`,
        `AOM_REMOTE`,
        `)" || die "the database backup failed; nothing was changed"`,
        '[ "$DRY_RUN" = 1 ] || [ -n "$BACKUP_FILE" ] || die "the database backup did not report a file; nothing was changed"',
        '[ "$DRY_RUN" = 1 ] || say "backup saved: $BACKUP_FILE"',
      ];
    case 'env_backup':
      return [
        ...stepNumberComment(i, 'save a copy of the settings file'),
        'remote "$APP_DIR" "$SHORT" "$DRY_RUN" <<\'AOM_REMOTE\'',
        'set -eu',
        'dir=$1; short=$2; dry=$3',
        '[ -f "$dir/.env" ] || { echo "AOM: there is no .env in $dir" >&2; exit 41; }',
        'bak="$dir/.env.bak-before-$short"',
        'if [ "$dry" = 1 ]; then echo "would: save a copy of the settings file as $bak" >&2; exit 0; fi',
        'if [ -e "$bak" ]; then echo "settings copy already exists: $bak" >&2; else cp -p -- "$dir/.env" "$bak"; echo "settings copy saved: $bak" >&2; fi',
        'AOM_REMOTE',
      ];
    case 'build_image_local':
      return [
        ...stepNumberComment(i, 'build the app image from the approved version'),
        'type -P docker >/dev/null 2>&1 || die "docker is not installed on this computer"',
        sh`case "$CHECKOUT" in /*) ;; *) die "AOM_DEPLOY_CHECKOUT must be a full path" ;; esac`,
        'if docker image inspect "$TAG" >/dev/null 2>&1; then',
        '  say "image $TAG already exists here"',
        'elif [ "$DRY_RUN" = 1 ]; then',
        '  would "build $TAG from the approved version"',
        'else',
        '  docker build -t "$TAG" "$CHECKOUT"',
        'fi',
      ];
    case 'ship_image_ssh':
      return [
        ...stepNumberComment(i, 'copy the image to the server'),
        'if rsh "docker image inspect$(rquote "$TAG")" </dev/null >/dev/null 2>&1; then',
        '  say "image $TAG is already on the server"',
        'elif [ "$DRY_RUN" = 1 ]; then',
        '  would "copy $TAG to the server"',
        'else',
        `  docker save "$TAG" | gzip | rsh 'gunzip | docker load'`,
        'fi',
      ];
    case 'set_image_var':
      return [
        ...stepNumberComment(i, 'switch the server to the new version'),
        'if [ "$DRY_RUN" = 1 ]; then',
        '  would "set $IMAGE_VAR=$TAG in $APP_DIR/.env (now: ${CURRENT_IMAGE:-not set})"',
        'else',
        '  SWITCHED=1',
        '  set_image_var "$TAG"',
        'fi',
      ];
    case 'write_override':
      return [
        ...stepNumberComment(
          i,
          `switch the server to the new version (${OVERRIDE_NAME}, your compose file is not edited)`,
        ),
        'if [ "$DRY_RUN" = 1 ]; then',
        `  would "name $TAG as the image of $SERVICE in $APP_DIR/${OVERRIDE_NAME} (now: \${RUNNING_IMAGE:-nothing}); your compose file is not changed"`,
        'else',
        '  SWITCHED=1',
        '  write_override "$TAG"',
        'fi',
      ];
    case 'push_image_registry':
      return [
        ...stepNumberComment(i, 'upload the image to the registry'),
        'if [ "$DRY_RUN" = 1 ]; then',
        '  would "upload $TAG to the registry $REGISTRY"',
        'else',
        '  docker push "$TAG" || die "could not upload $TAG to the registry $REGISTRY (is it reachable from this computer, and are you signed in to it?)"',
        'fi',
      ];
    case 'pull_image_ssh':
      return [
        ...stepNumberComment(i, 'the server downloads the image from the registry'),
        'if rsh "docker image inspect$(rquote "$TAG")" </dev/null >/dev/null 2>&1; then',
        '  say "image $TAG is already on the server"',
        'elif [ "$DRY_RUN" = 1 ]; then',
        '  would "let the server download $TAG from the registry $REGISTRY"',
        'else',
        '  rsh "docker pull$(rquote "$TAG")" </dev/null || die "the server could not download $TAG from the registry $REGISTRY (is the registry reachable from the server, and does its Docker trust it?)"',
        'fi',
      ];
    case 'ship_source_ssh':
      return [
        ...stepNumberComment(i, 'put the approved version’s files on the server'),
        sh`SRC_DEST="$SRC_DIR/$SHORT"`,
        // readers accept both marker names; the writer below still writes the old one (see doneFunction)
        'if rsh "test -f$(rquote "$SRC_DEST/.aom-complete") || test -f$(rquote "$SRC_DEST/.guildwise-complete")" </dev/null >/dev/null 2>&1; then',
        '  say "the files of $SHORT are already on the server"',
        'elif [ "$DRY_RUN" = 1 ]; then',
        '  would "copy the approved version’s files to $SRC_DEST on the server"',
        'else',
        '  [ -d "$CHECKOUT" ] || die "AOM_DEPLOY_CHECKOUT is not a folder"',
        '  git -C "$CHECKOUT" rev-parse --git-dir >/dev/null 2>&1 || die "the approved files are not a git checkout, so they cannot be sent safely (a plain folder can hold settings and secrets that are not part of the version); nothing was changed"',
        '  rsh "mkdir -p --$(rquote "$SRC_DEST")" </dev/null || die "could not create $SRC_DEST on the server"',
        '  git -C "$CHECKOUT" archive --format=tar "$COMMIT" | rsh "tar -x -f - -C$(rquote "$SRC_DEST")"',
        '  rsh "touch$(rquote "$SRC_DEST/.aom-complete")" </dev/null',
        '  # keep the newest 3 copies of the files; nothing else in the folder is touched',
        '  remote "$SRC_DIR" "$SHORT" <<\'AOM_REMOTE\' || true',
        'set -eu',
        'd=$1; cur=$2',
        `ls -1t -- "$d" 2>/dev/null | grep -E '^[0-9a-f]{12}$' | tail -n +4 | while IFS= read -r old; do [ "$old" = "$cur" ] || rm -rf -- "$d/$old"; done`,
        'AOM_REMOTE',
        'fi',
      ];
    case 'build_image_server':
      return [
        ...stepNumberComment(i, `the server builds ${env.app.service}`),
        'remote "$APP_DIR" "$COMPOSE_FILE" "$SERVICE" "$TAG" "$SRC_DEST" "$DRY_RUN" ' +
          (env.app.composeProject ? '"$COMPOSE_PROJECT"' : '""') +
          " <<'AOM_REMOTE'",
        'set -eu',
        'dir=$1; file=$2; svc=$3; tag=$4; ctx=$5; dry=$6; proj=$7',
        'cd "$dir"',
        'pa=(-f "$file"); [ -z "$proj" ] || pa=(-p "$proj" -f "$file")',
        'if [ "$dry" = 1 ]; then dc "${pa[@]}" config -q; echo "would build $tag on the server from the copied files" >&2; exit 0; fi',
        'if docker image inspect "$tag" >/dev/null 2>&1; then echo "image $tag already exists on the server" >&2; exit 0; fi',
        'tmpd=$(mktemp -d); trap \'rm -rf -- "$tmpd"\' EXIT',
        `printf 'services:\\n  %s:\\n    image: "%s"\\n    build:\\n      context: "%s"\\n' "$svc" "$tag" "$ctx" > "$tmpd/build.yml"`,
        'dc "${pa[@]}" -f "$tmpd/build.yml" build "$svc" </dev/null',
        'AOM_REMOTE',
      ];
    case 'compose_up_remote':
      return [
        ...stepNumberComment(i, `restart only ${env.app.service} on the server`),
        'if [ "$DRY_RUN" = 1 ]; then',
        '  compose_up_remote 1',
        'else',
        '  compose_up_remote 0',
        'fi',
      ];
    case 'compose_run':
      return [
        ...stepNumberComment(i, s.label),
        `RUN_SERVICE=${shq(s.service ?? env.app.service)}`,
        'if [ "$DRY_RUN" = 1 ]; then',
        `  compose_run_remote 1 "$RUN_SERVICE" ${s.argv.map(shq).join(' ')}`,
        'else',
        `  compose_run_remote 0 "$RUN_SERVICE" ${s.argv.map(shq).join(' ')} || die "the database updates failed; the app was not restarted"`,
        'fi',
      ];
    case 'custom_command':
      return [
        ...stepNumberComment(i, s.label),
        'if [ "$DRY_RUN" = 1 ]; then',
        `  would ${shq(s.label)}`,
        'else',
        s.where === 'server'
          ? `  rsh "$(rquote ${s.argv.map(shq).join(' ')})" </dev/null`
          : `  ${customArgv(s)}`,
        'fi',
      ];
    default:
      return [
        `# step ${i + 1}: ${s.kind} is not available on a server`,
        'die "this step is not available here"',
      ];
  }
}

function sshTail(env: SetupEnv): string[] {
  const out: string[] = ['', '# the end: check, go back if needed'];
  out.push(
    'if [ "$DRY_RUN" = 1 ]; then',
    env.health.kind === 'http'
      ? '  would "check $HEALTH_URL answers, and put the previous version back if it does not"'
      : '  would "let Guildwise check the site"',
    '  say "dry run finished: nothing was changed"',
    '  exit 0',
    'fi',
  );
  if (env.health.kind === 'http')
    out.push(
      'if ! wait_healthy "$HEALTH_TIMEOUT"; then',
      '  say "the site did not become healthy within ${HEALTH_TIMEOUT}s"',
      '  die "the update failed (the previous version is put back when it can be)"',
      'fi',
    );
  out.push('FINISHED=1');
  out.push('', 'done_line');
  return out;
}

// ------------------------------------------------------------------------------------------------ recipe + bundle

function recipeEnv(env: SetupEnv): Record<string, unknown> {
  const h = env.health;
  const health =
    h.kind === 'http'
      ? { kind: 'http', url: h.url, expect: h.expect }
      : h.kind === 'tcp'
        ? { kind: 'tcp', port: h.port }
        : h.kind === 'log'
          ? { kind: 'log', regex: h.regex }
          : { kind: 'none', graceSec: h.graceSec };
  return {
    name: env.name,
    target: env.target,
    script: shellPath(env.name),
    trigger: env.trigger.length === 1 ? env.trigger[0] : env.trigger,
    timeoutSec: env.timeoutSec,
    health,
    ...(env.secrets.length ? { secrets: env.secrets } : {}),
    ...(env.envFile ? { envFile: env.envFile } : {}),
    docker: true,
    releasedBy: env.releasedBy,
    gate: env.gate,
  };
}

const sha = (s: string) => sha256Hex(s);

/** The content hash of generated files (the same listing hash the Owner approves, over these files). */
export function compiledHash(files: readonly CompiledFile[]): string {
  const entries: BundleEntry[] = files.map((f) => ({ path: f.path, mode: f.mode, sha256: sha(f.content) }));
  return bundleHash(entries);
}

/** The script of one guided environment (also used to detect a hand edit). */
export function compileEnvScript(setup: DeliverySetup, env: SetupEnv): string {
  if (env.runtime === 'direct') return directScript(setup, env);
  return env.hosting === 'ssh' ? sshScript(setup, env) : localScript(setup, env);
}

/**
 * Validates and compiles. `customScripts` holds the text of hand-written scripts of `custom` environments; a custom
 * environment without text keeps the file that is in `delivery/` now (`keep`).
 */
export function compileSetup(
  input: unknown,
  opts: { customScripts?: Record<string, string> } = {},
): CompileResult {
  const parsed = DeliverySetupSchema.safeParse(input);
  if (!parsed.success)
    return {
      ok: false,
      issues: parsed.error.issues.map((i) => `${i.path.join('.') || 'setup'}: ${i.message}`).slice(0, 20),
    };
  const setup: DeliverySetup = { ...parsed.data, generator: SETUP_GENERATOR };
  const issues: string[] = [];
  for (const e of setup.environments)
    if (e.health.kind === 'http' && /\$\{(?!appUrl\})/.test(e.health.url))
      issues.push(`${e.name}: only \${appUrl} can be used in the health address`);
  for (const e of setup.environments)
    if (e.mode === 'guided' && e.health.kind === 'http' && e.health.url.includes('${appUrl}')) {
      if (!e.app.appUrl)
        issues.push(`${e.name}: the health check uses the app address, but no app address is set`);
    }
  if (issues.length) return { ok: false, issues };

  const files: CompiledFile[] = [];
  const keep: string[] = [];
  for (const e of setup.environments) {
    const path = shellPath(e.name);
    if (e.mode === 'guided') files.push({ path, mode: '755', content: compileEnvScript(setup, e) });
    else if (opts.customScripts?.[e.name] !== undefined)
      files.push({ path, mode: '755', content: opts.customScripts[e.name] as string });
    else keep.push(path);
  }
  const recipe = { version: RECIPE_VERSION, environments: setup.environments.map(recipeEnv) } as {
    version: 1;
    environments: Array<Record<string, unknown>>;
  };
  const recipeText = `# Generated by Guildwise ${SETUP_GENERATOR} from ${SETUP_FILE}. Edit in the guided view.\n${stringifyYaml(recipe, { lineWidth: 0 })}`;
  files.push({ path: RECIPE_FILE, mode: '644', content: recipeText });
  files.push({ path: SETUP_FILE, mode: '644', content: `${JSON.stringify(setup, null, 2)}\n` });
  files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  return { ok: true, files, keep, recipe, hash: compiledHash(files), setup };
}

