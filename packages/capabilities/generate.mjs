#!/usr/bin/env node
// Compiles packages/capabilities/{skills,personas,playbooks}/** into packages/shared/src/capabilities/builtin-data.ts.
// Run `node packages/capabilities/generate.mjs` after editing a built-in capability; `--check` only verifies the file is current.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const out = join(root, '..', 'shared', 'src', 'capabilities', 'builtin-data.ts');

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

export function build() {
  const files = {};
  for (const top of ['skills', 'personas', 'playbooks'])
    for (const p of walk(join(root, top)).sort())
      files[relative(root, p).split('\\').join('/')] = readFileSync(p, 'utf8').replace(/\r\n/g, '\n');
  return `// GENERATED by packages/capabilities/generate.mjs from packages/capabilities/**. Do not edit by hand.
export const BUILTIN_CAPABILITY_FILES: Record<string, string> = ${JSON.stringify(files, null, 2)};
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = build();
  if (process.argv.includes('--check')) {
    let cur = '';
    try {
      cur = readFileSync(out, 'utf8');
    } catch {}
    if (cur !== text) {
      console.error('builtin-data.ts is out of date: run node packages/capabilities/generate.mjs');
      process.exit(1);
    }
  } else writeFileSync(out, text);
}
