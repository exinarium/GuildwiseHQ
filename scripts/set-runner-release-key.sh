#!/usr/bin/env bash
# Commits the owner's minisign PUBLIC key as the official runner release key (core DESIGN R18-U "Release step", step 1):
#
#   scripts/set-runner-release-key.sh <file.pub>
#
# Checks that the file is a minisign public key (first line "untrusted comment:", second line the base64 of 42 bytes
# starting with "Ed") and refuses anything that looks like a secret key. Writes
#   apps/runner/release-key/guildwise-runner-release.pub
#   packages/shared/src/security/release-key.ts   (generated; the runner and the server's proof check read it)
# Then review and commit both files (one commit on development). Until this runs the repository holds the PLACEHOLDER,
# which `official` image builds and the runner's update check refuse.
set -euo pipefail
cd "$(dirname "$0")/.."
PUB="${1:-}"
[ -n "$PUB" ] || { echo "usage: $0 <file.pub>" >&2; exit 2; }
LINE="$(node scripts/runner-key-check.mjs "$PUB")"
ID="$(node scripts/runner-key-check.mjs --id "$PUB")"
OUT_PUB="apps/runner/release-key/guildwise-runner-release.pub"
OUT_TS="packages/shared/src/security/release-key.ts"
mkdir -p "$(dirname "$OUT_PUB")" "$(dirname "$OUT_TS")"
printf 'untrusted comment: minisign public key %s\n%s\n' "$ID" "$LINE" >"$OUT_PUB"
# The layout is what biome's formatter prints (a key line is always 56 characters, so the value goes on its own line):
# `npx biome check .` stays clean after a run.
cat >"$OUT_TS" <<TS
// GENERATED by scripts/set-runner-release-key.sh from apps/runner/release-key/guildwise-runner-release.pub.
// Do not edit by hand. Runner releases are signed with the matching secret key, which never leaves the owner's machine.

/** The official minisign public key line (\`RW...\`) that runner releases are signed with, or \`PLACEHOLDER\`. */
export const OFFICIAL_RUNNER_RELEASE_PUBKEY: string =
  '$LINE';
/** Its key id (16 upper-case hex characters), or null while it is the placeholder. */
export const OFFICIAL_RUNNER_RELEASE_KEY_ID: string | null = '$ID';
TS
echo "official runner release key set to $ID:"
echo "  $OUT_PUB"
echo "  $OUT_TS"
echo "Review and commit both files."
